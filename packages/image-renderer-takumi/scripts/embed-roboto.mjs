// Regenerate with `node packages/image-renderer-takumi/scripts/embed-roboto.mjs`.
// Normal builds are offline. This command downloads and compresses the pinned Roboto font.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const revision = '5bd87dfc525c8a0d1d8529d3684716e00c3fc59a';
const base = `https://raw.githubusercontent.com/google/fonts/${revision}/ofl/roboto/`;
async function download(path, sha256) {
  const response = await fetch(base + path);
  assert(response.ok, `${path}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  assert.equal(createHash('sha256').update(bytes).digest('hex'), sha256, path);
  return bytes;
}

const [ttf, license] = await Promise.all([
  download(
    'Roboto%5Bwdth,wght%5D.ttf',
    'd7598e12c5dbef095ff8272cfc55da0250bd07fbdecbac8a530b9b277872a134',
  ),
  download('OFL.txt', '061402327a96aadb0bfb694a960ed289ecd38d383e396243831ab81feb109c41'),
]);

const temporary = await mkdtemp(`${tmpdir()}/void-roboto-`);
let woff2;
try {
  const input = `${temporary}/Roboto.ttf`;
  const output = `${temporary}/Roboto.woff2`;
  await writeFile(input, ttf);
  execFileSync('vp', ['dlx', '--package', 'wawoff2@2.0.1', 'woff2_compress.js', input, output], {
    stdio: 'inherit',
  });
  woff2 = await readFile(output);
  assert.equal(
    createHash('sha256').update(woff2).digest('hex'),
    'ac391ddf3c31120658c1916d78225cbd0107c1cde20cc2a3e4cc789aea9d194b',
  );
} finally {
  await rm(temporary, { recursive: true, force: true });
}

// Read Roboto's Unicode cmap (format 4), not a script-wide approximation.
// Glyph 0 is .notdef and must never count as coverage.
let cmap;
for (let i = 0; i < ttf.readUInt16BE(4); i++) {
  const record = 12 + i * 16;
  if (ttf.toString('ascii', record, record + 4) === 'cmap') {
    cmap = ttf.readUInt32BE(record + 8);
  }
}
assert.notEqual(cmap, undefined);
let format4;
for (let i = 0; i < ttf.readUInt16BE(cmap + 2); i++) {
  const offset = cmap + ttf.readUInt32BE(cmap + 4 + i * 8 + 4);
  const platform = ttf.readUInt16BE(cmap + 4 + i * 8);
  if (ttf.readUInt16BE(offset) === 4 && (platform === 0 || platform === 3)) {
    format4 = offset;
    break;
  }
}
assert.notEqual(format4, undefined);
const count = ttf.readUInt16BE(format4 + 6) / 2;
const ranges = [];
for (let i = 0; i < count; i++) {
  const end = ttf.readUInt16BE(format4 + 14 + i * 2);
  const start = ttf.readUInt16BE(format4 + 16 + (count + i) * 2);
  const delta = ttf.readInt16BE(format4 + 16 + (count * 2 + i) * 2);
  const offset = format4 + 16 + (count * 3 + i) * 2;
  const relative = ttf.readUInt16BE(offset);
  for (let point = start; point <= end; point++) {
    const glyph = relative ? ttf.readUInt16BE(offset + relative + (point - start) * 2) : point;
    if ((relative && glyph === 0) || ((glyph + delta) & 0xffff) === 0) {
      continue;
    }
    const previous = ranges.at(-1);
    if (previous && previous[1] + 1 === point) {
      previous[1] = point;
    } else {
      ranges.push([point, point]);
    }
  }
}

const output = new URL('../src/roboto-font.ts', import.meta.url);
await writeFile(
  output,
  `/**
 * Generated by scripts/embed-roboto.mjs. Do not edit.
 * Roboto variable font from google/fonts at ${revision}, compressed to WOFF2.
 * Copyright 2011 The Roboto Project Authors (https://github.com/googlefonts/roboto-classic).
 * SIL Open Font License 1.1: see licenses/Roboto.txt in the @void/image-renderer-takumi package.
 */

export const robotoCoverage: ReadonlyArray<readonly [number, number]> = [
${ranges.map(([start, end]) => `  [0x${start.toString(16)}, 0x${end.toString(16)}],`).join('\n')}
];

let bytes: Uint8Array | undefined;

export function robotoData(): Uint8Array {
  return bytes ??= base64ToBytes('${woff2.toString('base64')}');
}

/** Decode the embedded font without depending on Node.js globals. */
function base64ToBytes(value: string): Uint8Array {
  const binary = atob(value);
  const out = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    out[i] = binary.charCodeAt(i);
  }
  return out;
}
`,
);
await mkdir(new URL('../licenses/', import.meta.url), { recursive: true });
await writeFile(new URL('../licenses/Roboto.txt', import.meta.url), license);
execFileSync('vp', ['fmt', fileURLToPath(output)], { stdio: 'inherit' });
console.log(`Embedded ${woff2.length} bytes of Roboto with ${ranges.length} coverage ranges.`);
