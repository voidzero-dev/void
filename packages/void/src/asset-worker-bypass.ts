/**
 * Build-time decision for letting Cloudflare serve fingerprinted build files
 * without starting the Worker. Native Cloudflare builds of apps with no global
 * middleware and no edge rules gain nothing from running the Worker for those
 * files: the Worker would only copy the asset response. Skipping it makes
 * those requests free static requests and keeps auth and its session read off
 * them. Each file gets its own negative `run_worker_first` rule, because a
 * request matching a negative rule never reaches the Worker, even when the
 * file is missing. Misses and other paths in the folder keep the Worker's
 * not-found, SPA and page handling.
 * `routing.alwaysUseHttps` alone does not block this: hashed files are only
 * linked from pages the Worker has already moved to HTTPS.
 *
 * The asset layer does not know which files are fingerprinted, so a generated
 * `_headers` file gives every bypassed chunk the immutable policy the Worker
 * would have set.
 *
 * An `output: "static"` Pages build goes further when nothing site-wide must
 * run first (auth, live, `routing.alwaysUseHttps`): every file answers first,
 * and only paths with server code reach the Worker first. A page without a
 * server module prerenders the HTML the Worker would render, so its file can
 * answer. Hashed files keep their
 * immutable policy from the generated `_headers`, or stay on the Worker when
 * it cannot list them.
 */

import { VOID_INTERNAL_WORKER_FIRST } from './asset-routing.ts';

export const GENERATED_ASSET_HEADERS_MARKER =
  '# Generated by Void: immutable caching for fingerprinted build files. Do not edit.';
/** Cloudflare accepts at most 100 `run_worker_first` rules. */
const MAX_RUN_WORKER_FIRST_RULES = 100;
/** Cloudflare limits each `run_worker_first` rule to 100 characters. */
const MAX_RUN_WORKER_FIRST_RULE_LENGTH = 100;
/** Cloudflare accepts at most 100 `_headers` rules. */
const MAX_HEADERS_RULES = 100;

const IMMUTABLE_CACHE_CONTROL = 'public, max-age=31536000, immutable';
const AUTH_PATTERNS = ['/api/auth/*'];

export type AssetWorkerBypassFacts = {
  /** `assets.run_worker_first` as the Worker build wrote it. */
  runWorkerFirst: unknown;
  /** `assets.not_found_handling` from the built Worker config. */
  notFoundHandling: unknown;
  /** Vite's resolved `base`. */
  base: string;
  hasMiddleware: boolean;
  authEnabled: boolean;
  liveEnabled: boolean;
  /** Keeps pages on the Worker, which a direct HTTP request for a page needs. */
  alwaysUseHttps: boolean;
  headerRuleCount: number;
  redirectRuleCount: number;
  fallbackRuleCount: number;
  /** Whether `_headers` or `_redirects` exists in Vite's `publicDir`. */
  publicEdgeFiles: boolean;
  /** Every route, page, WebSocket, prerender and revalidate pattern. */
  patterns: Array<string>;
  /** Vite's `build.assetsDir`. */
  assetsDir: string;
  /** Fingerprinted files the manifest marks immutable, relative to the client root. */
  immutableFiles: Array<string>;
  /**
   * For an `output: "static"` Pages build, the patterns with server code:
   * routes, WebSockets, and pages that have a server module or parameters.
   */
  serverPatterns?: Array<string>;
};

export type AssetWorkerBypass = {
  /** The new `assets.run_worker_first`. */
  runWorkerFirst: Array<string>;
  /** The generated `_headers` text; null when no hashed file skips the Worker. */
  headers: string | null;
};

/** Trim surrounding slashes; null when nothing is left. */
export function normalizeAssetsDir(dir: string): string | null {
  let start = 0;
  let end = dir.length;
  while (start < end && dir[start] === '/') {
    start++;
  }
  while (end > start && dir[end - 1] === '/') {
    end--;
  }
  const trimmed = dir.slice(start, end);
  return trimmed === '' || trimmed === '.' ? null : trimmed;
}

/**
 * Whether a route pattern can match a path below `/<dir>/`. Parameters,
 * wildcards and patterns with more segments than the directory count as a
 * match, so the answer errs towards keeping the Worker in front.
 */
export function patternCanReachUnder(pattern: string, dir: string): boolean {
  const patternSegments = (pattern.startsWith('/') ? pattern.slice(1) : pattern).split('/');
  const dirSegments = (dir.startsWith('/') ? dir.slice(1) : dir).split('/');
  for (let i = 0; i < dirSegments.length; i++) {
    const segment = patternSegments[i];
    if (segment === undefined) {
      return false;
    }
    if (segment.includes('*') || segment.includes('{')) {
      return true;
    }
    if (segment.startsWith(':')) {
      continue;
    }
    if (segment.toLowerCase() !== dirSegments[i].toLowerCase()) {
      return false;
    }
  }
  return patternSegments.length > dirSegments.length;
}

/**
 * Characters that are plain text in both a `_headers` path and a
 * `run_worker_first` rule. `*`, `:` and `!` have meaning there, and anything
 * that needs URL encoding would not match the request path as written.
 */
function isPlainPath(path: string): boolean {
  for (const char of path) {
    const plain =
      (char >= 'a' && char <= 'z') ||
      (char >= 'A' && char <= 'Z') ||
      (char >= '0' && char <= '9') ||
      char === '-' ||
      char === '_' ||
      char === '.' ||
      char === '~' ||
      char === '/';
    if (!plain) {
      return false;
    }
  }
  return path.split('/').every((segment) => segment !== '' && segment !== '.' && segment !== '..');
}

/**
 * Whether `run_worker_first` is the rule an earlier bypass wrote. A watch
 * rebuild of only the client still finds it, because the Worker build that
 * would write `['/**']` again did not run.
 */
export function isAssetBypassRule(runWorkerFirst: unknown, assetsDir: string): boolean {
  const dir = normalizeAssetsDir(assetsDir);
  return (
    dir !== null &&
    Array.isArray(runWorkerFirst) &&
    runWorkerFirst.length > 1 &&
    runWorkerFirst[0] === '/**' &&
    runWorkerFirst
      .slice(1)
      .every((rule) => typeof rule === 'string' && rule.startsWith('!/' + dir + '/'))
  );
}

/** The bypass this build can use, or null when any rule keeps the Worker in front. */
export function resolveAssetWorkerBypass(facts: AssetWorkerBypassFacts): AssetWorkerBypass | null {
  const { runWorkerFirst } = facts;
  if (
    !(
      Array.isArray(runWorkerFirst) &&
      runWorkerFirst.length === 1 &&
      runWorkerFirst[0] === '/**'
    ) ||
    facts.notFoundHandling !== 'none' ||
    facts.base !== '/' ||
    facts.hasMiddleware ||
    facts.headerRuleCount > 0 ||
    facts.redirectRuleCount > 0 ||
    facts.fallbackRuleCount > 0 ||
    facts.publicEdgeFiles
  ) {
    return null;
  }
  const assetsDir = normalizeAssetsDir(facts.assetsDir);
  // The Worker gives the immutable policy only to hashed files in the assets folder.
  const files =
    assetsDir === null
      ? []
      : [...new Set(facts.immutableFiles)]
          .filter((file) => file.startsWith(assetsDir + '/'))
          .sort();
  return (
    resolveStaticPageBypass(facts, assetsDir, files) ??
    resolveHashedFileBypass(facts, assetsDir, files)
  );
}

/** One negative rule per hashed file, so only those files skip the Worker. */
function resolveHashedFileBypass(
  facts: AssetWorkerBypassFacts,
  assetsDir: string | null,
  files: Array<string>,
): AssetWorkerBypass | null {
  if (!assetsDir || !isPlainPath(assetsDir)) {
    return null;
  }
  const patterns = [
    ...facts.patterns,
    // Void's own Worker paths. They are not in the route scan.
    ...VOID_INTERNAL_WORKER_FIRST,
    ...(facts.authEnabled ? AUTH_PATTERNS : []),
  ];
  if (patterns.some((pattern) => patternCanReachUnder(pattern, assetsDir))) {
    return null;
  }
  const rules = ['/**', ...files.map((file) => '!/' + file)];
  if (
    files.length === 0 ||
    files.some((file) => !isPlainPath(file)) ||
    !fitsRunWorkerFirstLimits(rules)
  ) {
    return null;
  }
  return { runWorkerFirst: rules, headers: renderGeneratedAssetHeaders(files) };
}

/**
 * Void's own paths, then every server pattern widened to the static prefix
 * before its first parameter: matching too much only keeps the Worker in
 * front. A request that matches no file still reaches the Worker, since these
 * builds use `not_found_handling: 'none'`. Hashed files get the generated
 * `_headers`, or stay on the Worker when it cannot list them all. Null when
 * site-wide behavior must run first or a pattern covers every path.
 */
function resolveStaticPageBypass(
  facts: AssetWorkerBypassFacts,
  assetsDir: string | null,
  files: Array<string>,
): AssetWorkerBypass | null {
  if (!facts.serverPatterns || facts.authEnabled || facts.liveEnabled || facts.alwaysUseHttps) {
    return null;
  }
  const rules = new Set<string>();
  for (const pattern of facts.serverPatterns) {
    const patternRules = workerPathRules(pattern);
    if (patternRules === null) {
      return null;
    }
    for (const rule of patternRules) {
      rules.add(rule);
    }
  }
  let headers: string | null = null;
  if (files.length > MAX_HEADERS_RULES || !files.every(isPlainPath)) {
    if (!assetsDir || !isPlainPath(assetsDir)) {
      return null;
    }
    rules.add('/' + assetsDir + '/*');
  } else if (files.length > 0) {
    headers = renderGeneratedAssetHeaders(files);
  }
  const runWorkerFirst = [...VOID_INTERNAL_WORKER_FIRST, ...[...rules].sort()];
  return fitsRunWorkerFirstLimits(runWorkerFirst) ? { runWorkerFirst, headers } : null;
}

/**
 * The rules covering every path `pattern` matches; null when that is every
 * path. A trailing `*` also matches the path before it: `/api/*` matches `/api`.
 */
function workerPathRules(pattern: string): Array<string> | null {
  if (pattern === '/') {
    return ['/'];
  }
  const segments = (pattern.startsWith('/') ? pattern.slice(1) : pattern).split('/');
  const dynamic = segments.findIndex(
    (segment) => segment.startsWith(':') || segment.includes('*') || segment.includes('{'),
  );
  if (dynamic === 0) {
    return null;
  }
  const prefix = (dynamic === -1 ? segments : segments.slice(0, dynamic)).join('/');
  if (!isPlainPath(prefix)) {
    return null;
  }
  if (dynamic === -1) {
    return ['/' + prefix];
  }
  const rule = '/' + prefix + '/*';
  return dynamic === segments.length - 1 && segments[dynamic] === '*'
    ? ['/' + prefix, rule]
    : [rule];
}

function fitsRunWorkerFirstLimits(rules: Array<string>): boolean {
  return (
    rules.length <= MAX_RUN_WORKER_FIRST_RULES &&
    rules.every((rule) => rule.length <= MAX_RUN_WORKER_FIRST_RULE_LENGTH)
  );
}

/** One immutable rule per file after the marker line. */
function renderGeneratedAssetHeaders(files: Array<string>): string {
  const lines = [GENERATED_ASSET_HEADERS_MARKER];
  for (const file of files) {
    lines.push('/' + file, '  Cache-Control: ' + IMMUTABLE_CACHE_CONTROL);
  }
  return lines.join('\n') + '\n';
}

/** Whether a `_headers` file is the one Void generated. */
export function isGeneratedAssetHeaders(text: string): boolean {
  const newline = text.indexOf('\n');
  let firstLine = newline === -1 ? text : text.slice(0, newline);
  if (firstLine.endsWith('\r')) {
    firstLine = firstLine.slice(0, -1);
  }
  return firstLine === GENERATED_ASSET_HEADERS_MARKER;
}
