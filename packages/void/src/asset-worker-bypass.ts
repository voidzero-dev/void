/**
 * Build-time decision for letting Cloudflare serve fingerprinted build files
 * without starting the Worker. Native Cloudflare builds of apps with no global
 * middleware and no edge rules gain nothing from running the Worker for
 * `/<assetsDir>/*`: the Worker would only copy the asset response. Skipping it
 * makes those requests free static requests and keeps auth and its session
 * read off them.
 *
 * The asset layer does not know which files are fingerprinted, so a generated
 * `_headers` file lists every manifest-proven chunk with the immutable policy
 * the Worker would have set. Files it does not list keep Cloudflare's default
 * revalidation policy, which matches what the Worker returns for them today.
 */

export const GENERATED_ASSET_HEADERS_MARKER =
  '# Generated by Void: immutable caching for fingerprinted build files. Do not edit.';
/** Cloudflare accepts at most 100 `_headers` rules. */
export const MAX_ASSET_HEADER_RULES = 100;
/** Cloudflare limits each `run_worker_first` rule to 100 characters. */
export const MAX_RUN_WORKER_FIRST_RULE_LENGTH = 100;

const IMMUTABLE_CACHE_CONTROL = 'public, max-age=31536000, immutable';
// Void's own Worker paths. They are not in the route scan.
const INTERNAL_PATTERNS = ['/__void/*'];
const AUTH_PATTERNS = ['/api/auth/*'];

export type AssetWorkerBypassFacts = {
  /** `assets.run_worker_first` from the built Worker config. */
  runWorkerFirst: unknown;
  /** `assets.not_found_handling` from the built Worker config. */
  notFoundHandling: unknown;
  /** Vite's resolved `base`. */
  base: string;
  hasMiddleware: boolean;
  authEnabled: boolean;
  headerRuleCount: number;
  redirectRuleCount: number;
  fallbackRuleCount: number;
  /** Whether `_headers` or `_redirects` exists in Vite's `publicDir`. */
  publicEdgeFiles: boolean;
  /** Every route, page, WebSocket, prerender and revalidate pattern. */
  patterns: Array<string>;
  /** Vite's `build.assetsDir`. */
  assetsDir: string;
  /** Fingerprinted files the manifest marks immutable, relative to the client root. */
  immutableFiles: Array<string>;
};

export type AssetWorkerBypass = {
  assetsDir: string;
  /** Immutable files under `assetsDir`, sorted. */
  files: Array<string>;
};

/** Trim surrounding slashes; null when nothing is left. */
export function normalizeAssetsDir(dir: string): string | null {
  let start = 0;
  let end = dir.length;
  while (start < end && dir[start] === '/') {
    start++;
  }
  while (end > start && dir[end - 1] === '/') {
    end--;
  }
  const trimmed = dir.slice(start, end);
  return trimmed === '' || trimmed === '.' ? null : trimmed;
}

/**
 * Whether a route pattern can match a path below `/<dir>/`. Parameters,
 * wildcards and patterns with more segments than the directory count as a
 * match, so the answer errs towards keeping the Worker in front.
 */
export function patternCanReachUnder(pattern: string, dir: string): boolean {
  const patternSegments = (pattern.startsWith('/') ? pattern.slice(1) : pattern).split('/');
  const dirSegments = (dir.startsWith('/') ? dir.slice(1) : dir).split('/');
  for (let i = 0; i < dirSegments.length; i++) {
    const segment = patternSegments[i];
    if (segment === undefined) {
      return false;
    }
    if (segment.includes('*') || segment.includes('{')) {
      return true;
    }
    if (segment.startsWith(':')) {
      continue;
    }
    if (segment.toLowerCase() !== dirSegments[i].toLowerCase()) {
      return false;
    }
  }
  return patternSegments.length > dirSegments.length;
}

/**
 * Characters that are plain text in both a `_headers` path and a
 * `run_worker_first` rule. `*`, `:` and `!` have meaning there, and anything
 * that needs URL encoding would not match the request path as written.
 */
function isPlainPath(path: string): boolean {
  for (const char of path) {
    const plain =
      (char >= 'a' && char <= 'z') ||
      (char >= 'A' && char <= 'Z') ||
      (char >= '0' && char <= '9') ||
      char === '-' ||
      char === '_' ||
      char === '.' ||
      char === '~' ||
      char === '/';
    if (!plain) {
      return false;
    }
  }
  return path.split('/').every((segment) => segment !== '' && segment !== '.' && segment !== '..');
}

/** The bypass this build can use, or null when any rule keeps the Worker in front. */
export function resolveAssetWorkerBypass(facts: AssetWorkerBypassFacts): AssetWorkerBypass | null {
  const { runWorkerFirst } = facts;
  if (
    !Array.isArray(runWorkerFirst) ||
    runWorkerFirst.length !== 1 ||
    runWorkerFirst[0] !== '/**' ||
    facts.notFoundHandling !== 'none' ||
    facts.base !== '/' ||
    facts.hasMiddleware ||
    facts.headerRuleCount > 0 ||
    facts.redirectRuleCount > 0 ||
    facts.fallbackRuleCount > 0 ||
    facts.publicEdgeFiles
  ) {
    return null;
  }
  const assetsDir = normalizeAssetsDir(facts.assetsDir);
  if (!assetsDir || !isPlainPath(assetsDir) || !withAssetBypassRule(['/**'], assetsDir)) {
    return null;
  }
  const patterns = [
    ...facts.patterns,
    ...INTERNAL_PATTERNS,
    ...(facts.authEnabled ? AUTH_PATTERNS : []),
  ];
  if (patterns.some((pattern) => patternCanReachUnder(pattern, assetsDir))) {
    return null;
  }
  const prefix = assetsDir + '/';
  const files = [...new Set(facts.immutableFiles)].filter((file) => file.startsWith(prefix)).sort();
  if (
    files.length === 0 ||
    files.length > MAX_ASSET_HEADER_RULES ||
    files.some((file) => !isPlainPath(file))
  ) {
    return null;
  }
  return { assetsDir, files };
}

/** `['/**']` plus the negative rule for the assets folder, or null when it cannot be added. */
export function withAssetBypassRule(
  runWorkerFirst: unknown,
  assetsDir: string,
): Array<string> | null {
  if (
    !Array.isArray(runWorkerFirst) ||
    runWorkerFirst.length !== 1 ||
    runWorkerFirst[0] !== '/**'
  ) {
    return null;
  }
  const rule = '!/' + assetsDir + '/*';
  return rule.length > MAX_RUN_WORKER_FIRST_RULE_LENGTH ? null : ['/**', rule];
}

/** The generated `_headers` text, or null when the files do not fit Cloudflare's rule limit. */
export function renderGeneratedAssetHeaders(files: Array<string>): string | null {
  if (files.length === 0 || files.length > MAX_ASSET_HEADER_RULES) {
    return null;
  }
  const lines = [GENERATED_ASSET_HEADERS_MARKER];
  for (const file of files) {
    lines.push('/' + file, '  Cache-Control: ' + IMMUTABLE_CACHE_CONTROL);
  }
  return lines.join('\n') + '\n';
}

/** Whether a `_headers` file is the one Void generated. */
export function isGeneratedAssetHeaders(text: string): boolean {
  const newline = text.indexOf('\n');
  let firstLine = newline === -1 ? text : text.slice(0, newline);
  if (firstLine.endsWith('\r')) {
    firstLine = firstLine.slice(0, -1);
  }
  return firstLine === GENERATED_ASSET_HEADERS_MARKER;
}
