export type WrapperFeatures = {
  /** Cron job definitions (from scanJobsSync). */
  crons: Array<{ name: string; filePath: string; crons: Array<string> }>;
  /** Queue consumer definitions (from scanQueuesSync). */
  queues: Array<{ name: string; filePath: string; bindingName: string }>;
  /** Whether migrations are present (framework deploys need a /__void/migrate endpoint). */
  hasMigrations?: boolean;
  /** Expose the readiness endpoint used by direct version activation. */
  readiness?: boolean;
  /** Preserve an authored metadata binding name for native readiness proof. */
  versionMetadataBinding?: string;
  /** Database dialect for migration handler. */
  migrationDialect?: 'sqlite' | 'postgresql' | 'mysql';
  /** Direct Cloudflare ISR policy; managed deployments cache in dispatch instead. */
  isr?: {
    revalidate: number | Record<string, number>;
    queryAllowlist?: Record<string, Array<string>>;
  };
};

export type WrapperResult = {
  /** Filename of the bundled entry module. */
  entryFilename: string;
  /** Absolute path to the directory containing the bundled output. */
  outputDir: string;
};

const BUNDLED_ENTRY_RE = /^index\.(?:m?js|cjs)$/;
// The env module that the app's `void/db` imports, so the jobs' request scope is the one it reads.
const envModuleFile = fileURLToPath(import.meta.resolve('#self/_env'));
const WRAPPER_MARKER = '// Generated by Void: deployment wrapper.';

function isGeneratedWrapper(source: string, originalName: string): boolean {
  return (
    source.startsWith(WRAPPER_MARKER) ||
    source.startsWith(`import original from "./${originalName}";\n`)
  );
}

export function selectBundledEntryFilename(outFiles: Array<string>): string {
  const entryFilename = outFiles.find((file) => BUNDLED_ENTRY_RE.test(file));
  if (!entryFilename) {
    throw new Error(
      `deploy: Bundled worker entry not found. Expected index.js, index.mjs, or index.cjs in bundle output. Found: ${outFiles.join(', ') || '(none)'}`,
    );
  }
  return entryFilename;
}

/**
 * Determine whether a wrapper is needed based on the features.
 */
export function needsWrapper(features: WrapperFeatures): boolean {
  return (
    features.crons.length > 0 ||
    features.queues.length > 0 ||
    !!features.hasMigrations ||
    !!features.readiness ||
    !!features.isr
  );
}

/**
 * Generate a wrapper entry in-place in the worker directory.
 *
 * - Preserves the original entry (e.g. `index.js` → `__original.js`)
 * - Compiles cron/queue handlers via a small Vite build
 * - Writes a wrapper module as the original entry name that imports
 *   the renamed original + compiled handlers
 *
 * The original worker code is never re-bundled.
 */
export async function generateWrapper(
  workerDir: string,
  workerMain: string,
  root: string,
  features: WrapperFeatures,
): Promise<void> {
  const ext = extname(workerMain) || '.js';
  const renamedName = `__original${ext}`;
  const mainPath = join(workerDir, workerMain);
  const originalPath = join(workerDir, renamedName);
  const alreadyWrapped = isGeneratedWrapper(readFileSync(mainPath, 'utf8'), renamedName);
  if (
    alreadyWrapped &&
    (!existsSync(originalPath) ||
      isGeneratedWrapper(readFileSync(originalPath, 'utf8'), renamedName))
  ) {
    throw new Error(
      'deploy: Original framework entry is missing or already wrapped. Rebuild the application before deploying.',
    );
  }

  // Compile cron/queue handlers if needed (small focused build — user source is TypeScript)
  let handlerFilename = '__void_handlers.mjs';
  if (features.crons.length > 0 || features.queues.length > 0) {
    const tmpDir = join(root, '.void', 'handlers');
    mkdirSync(tmpDir, { recursive: true });
    const config = readConfig(root);
    const handlersSource = generateHandlersSource(root, features, getDatabaseDialect(config));
    const handlersEntry = join(tmpDir, 'handlers.ts');
    writeFileSync(handlersEntry, handlersSource);

    const outDir = join(tmpDir, 'out');
    await build({
      root: tmpDir,
      logLevel: 'silent',
      // This focused build does not run voidPlugin(), so give it the app's `void/db` and
      // `@schema`. A PostgreSQL or MySQL driver comes prebuilt for workerd.
      plugins: [
        voidDbBundlerPlugin(root, {
          config,
          sqlDriver: (dialect, entry) =>
            bundleWorkerSqlDriver(dialect, entry, join(tmpDir, 'sql-driver')),
        }),
      ],
      resolve: {
        // Cron/queue scaffolds intentionally import their lightweight runtime helpers from the
        // public `void` entry. This focused build does not run voidPlugin(), so reproduce its
        // exact bare-import redirect here; otherwise Vite follows the plugin/CLI entry and pulls
        // Wrangler (including native keyring binaries) into the Worker handler bundle.
        alias: [
          {
            find: /^void$/,
            replacement: fileURLToPath(import.meta.resolve('void/handler')),
          },
        ],
      },
      build: {
        outDir,
        emptyOutDir: true,
        lib: {
          entry: handlersEntry,
          formats: ['es'],
          fileName: '__void_handlers',
        },
        rollupOptions: {
          external: [/^cloudflare:/, /^node:/],
        },
        minify: false,
        target: 'esnext',
      },
    });

    // Find the actual output filename and copy to worker dir
    const handlerFiles = readdirSync(outDir).filter((f) => f.startsWith('__void_handlers'));
    handlerFilename = handlerFiles[0] ?? '__void_handlers.mjs';
    copyFileSync(join(outDir, handlerFilename), join(workerDir, handlerFilename));
  }

  // Collect migrations and copy handler if needed
  let migrations: Array<{ name: string; sql: string }> | undefined;
  let migrationPlanBundle: MigrationPlanBundle | undefined;
  if (features.hasMigrations) {
    const { collectMigrations } = await import('../migrations/collect.ts');
    const { buildMigrationPlanBundle } = await import('../migrations/plan.ts');
    const migrationsDir = readProjectPaths(root).migrationsDir;
    migrations = collectMigrations(migrationsDir);
    migrationPlanBundle =
      features.migrationDialect === 'sqlite' ? buildMigrationPlanBundle(migrations) : undefined;
    const handlerName =
      features.migrationDialect === 'postgresql'
        ? 'migration-handler-pg'
        : features.migrationDialect === 'mysql'
          ? 'migration-handler-mysql'
          : 'migration-handler';
    const handlerFilename_ = `${handlerName}.mjs`;
    let handlerPath = join(import.meta.dirname, '..', 'runtime', `${handlerName}.ts`);
    if (!existsSync(handlerPath)) {
      handlerPath = join(import.meta.dirname, 'runtime', handlerFilename_);
    }
    if (!existsSync(handlerPath)) {
      handlerPath = join(import.meta.dirname, '..', 'runtime', handlerFilename_);
    }
    if (!existsSync(handlerPath)) {
      throw new Error(
        `Migration handler not found: ${handlerFilename_}. Run "pnpm -C packages/void build" first.`,
      );
    }
    await bundleMigrationHandler(
      root,
      workerDir,
      handlerPath,
      features.migrationDialect ?? 'sqlite',
    );
  }

  if (features.isr) {
    await bundleFrameworkIsr(root, workerDir);
  }

  // Write wrapper in place of original entry
  const wrapperSource = generateWrapperSource(
    renamedName,
    handlerFilename,
    features,
    migrations,
    migrationPlanBundle,
  );
  // Compile first, then atomically replace the entry. A failed build must leave
  // it usable; a repeated --skip-build must never copy the wrapper over the app.
  const stagedPath = `${mainPath}.${crypto.randomUUID()}.tmp`;
  try {
    writeFileSync(stagedPath, wrapperSource);
    if (!alreadyWrapped) {
      copyFileSync(mainPath, originalPath);
    }
    renameSync(stagedPath, mainPath);
  } finally {
    rmSync(stagedPath, { force: true });
  }
}

async function bundleFrameworkIsr(root: string, workerDir: string): Promise<void> {
  const entry = fileURLToPath(import.meta.resolve('@void/isr/runtime'));
  const tmpDir = join(root, '.void', 'isr');
  const outDir = join(tmpDir, 'out');
  mkdirSync(tmpDir, { recursive: true });
  await build({
    root: tmpDir,
    logLevel: 'silent',
    ssr: { noExternal: true },
    build: {
      outDir,
      emptyOutDir: true,
      minify: false,
      ssr: entry,
      target: 'esnext',
      rollupOptions: {
        input: entry,
        external: [/^cloudflare:/, /^node:/],
        output: {
          entryFileNames: '__void_isr.mjs',
          chunkFileNames: '__void_isr-[hash].mjs',
        },
      },
    },
  });
  for (const file of readdirSync(outDir)) {
    copyFileSync(join(outDir, file), join(workerDir, file));
  }
}

async function bundleMigrationHandler(
  root: string,
  workerDir: string,
  handlerPath: string,
  dialect: 'sqlite' | 'postgresql' | 'mysql',
): Promise<void> {
  const tmpDir = join(root, '.void', 'migration-handler');
  mkdirSync(tmpDir, { recursive: true });
  const outDir = join(tmpDir, 'out');
  const isPostgresql = dialect === 'postgresql';
  const isMysql = dialect === 'mysql';
  await build({
    root: tmpDir,
    logLevel: 'silent',
    resolve: isPostgresql
      ? { alias: pgWorkerAliases(handlerPath), conditions: WORKER_CONDITIONS }
      : undefined,
    // A build decides what is external by resolving from `root`, which sits in the app. npm,
    // Yarn and Bun hoist dependencies there, and workerd cannot load a bare import, so bundle
    // every package. Node built-ins stay external for the require shims below.
    ssr: {
      noExternal: true,
      ...(isPostgresql && { resolve: { conditions: WORKER_CONDITIONS } }),
    },
    build: {
      outDir,
      emptyOutDir: true,
      minify: false,
      ssr: handlerPath,
      target: 'esnext',
      rollupOptions: {
        input: handlerPath,
        external: SQL_WORKER_EXTERNAL,
        output: {
          entryFileNames: '__void_migration_handler.mjs',
          chunkFileNames: '__void_migration_handler-[hash].mjs',
        },
      },
    },
  });

  if (isPostgresql || isMysql) {
    patchWorkerRequireBundle(outDir, isPostgresql ? 'PostgreSQL' : 'MySQL', 'migration bundle');
  }
  for (const file of readdirSync(outDir)) {
    copyFileSync(join(outDir, file), join(workerDir, file));
  }
}

// workerd's conditions, then a browser build's, so packages pick their Worker builds.
const WORKER_CONDITIONS = ['workerd', 'worker', 'browser', 'module', 'import', 'default'];
const SQL_WORKER_EXTERNAL = [/^cloudflare:/, /^node:/, /^pgpass$/];

/** pg's workerd socket and its CommonJS pool, resolved from the pg that `fromPath` loads. */
function pgWorkerAliases(fromPath: string): Record<string, string> {
  return {
    'pg-cloudflare': resolvePgCloudflareWorkerdEntry(fromPath),
    'pg-pool': resolvePgCjsDependency(fromPath, 'pg-pool'),
  };
}

/**
 * Build the PostgreSQL or MySQL driver whose entry file is `main` as an ES module for workerd,
 * the way the migration handler bundles Void's own, and return its path. Bundlers that do not run
 * voidPlugin() import this module for `pg` or `mysql2`: their CommonJS handling breaks the
 * drivers in workerd. Each driver copy gets its own folder in `baseDir`. The same build gives
 * mysql2's `mysql2/promise` API as `promise.mjs` next to it, so both share one copy of the driver.
 */
export async function bundleWorkerSqlDriver(
  dialect: 'postgresql' | 'mysql',
  main: string,
  baseDir: string,
): Promise<string> {
  const packageName = dialect === 'postgresql' ? 'pg' : 'mysql2';
  const outDir = join(baseDir, createHash('sha256').update(main).digest('hex').slice(0, 12));
  mkdirSync(outDir, { recursive: true });
  const input: Record<string, string> = {
    [packageName]: writeDriverEntry(join(outDir, 'entry.mjs'), main),
  };
  const promise = dialect === 'mysql' ? resolveMysqlPromise(main) : undefined;
  if (promise !== undefined) {
    input.promise = writeDriverEntry(join(outDir, 'promise-entry.mjs'), promise);
  }
  const bundleDir = join(outDir, 'out');
  await build({
    root: outDir,
    logLevel: 'silent',
    resolve: {
      alias: dialect === 'postgresql' ? pgWorkerAliases(main) : {},
      conditions: WORKER_CONDITIONS,
    },
    ssr: { noExternal: true, resolve: { conditions: WORKER_CONDITIONS } },
    build: {
      outDir: bundleDir,
      emptyOutDir: true,
      minify: false,
      ssr: true,
      target: 'esnext',
      rollupOptions: {
        input,
        external: SQL_WORKER_EXTERNAL,
        output: {
          entryFileNames: '[name].mjs',
          chunkFileNames: `${packageName}-[hash].mjs`,
        },
      },
    },
  });
  patchWorkerRequireBundle(
    bundleDir,
    dialect === 'postgresql' ? 'PostgreSQL' : 'MySQL',
    'driver bundle',
  );
  return join(bundleDir, `${packageName}.mjs`);
}

/** Write an ES module at `entry` that exports the CommonJS module `file`, and return `entry`. */
function writeDriverEntry(entry: string, file: string): string {
  const names = Object.keys(createRequire(file)(file) as object).filter(
    (name) => name !== 'default' && /^[A-Za-z_$][\w$]*$/.test(name),
  );
  writeFileSync(
    entry,
    `import driver from ${JSON.stringify(toSlash(file))};\nexport default driver;\nexport const { ${names.join(', ')} } = driver;\n`,
  );
  return entry;
}

/** The `mysql2/promise` file of the mysql2 copy whose entry file is `main`, if it has one. */
function resolveMysqlPromise(main: string): string | undefined {
  try {
    return createRequire(main).resolve('mysql2/promise');
  } catch {
    return undefined;
  }
}

/** `bundle` names the bundle in the error a failed require throws. */
function patchWorkerRequireBundle(
  outDir: string,
  database: 'PostgreSQL' | 'MySQL',
  bundle: string,
): void {
  for (const file of readdirSync(outDir)) {
    if (!file.endsWith('.mjs') && !file.endsWith('.js')) {
      continue;
    }
    const path = join(outDir, file);
    const code = readFileSync(path, 'utf-8');
    const transformed = transformWorkerRequireBundle(
      code,
      file,
      database === 'PostgreSQL' ? pgWorkerRequireShim(bundle) : mysqlWorkerRequireShim(bundle),
      database,
    );
    if (transformed !== code) {
      writeFileSync(path, transformed);
    }
  }
}

function createPgPackageRequire(fromPath: string): NodeJS.Require {
  const fromRequire = createRequire(fromPath);
  return createRequire(fromRequire.resolve('pg/package.json'));
}

function resolvePgCjsDependency(fromPath: string, specifier: string): string {
  return createPgPackageRequire(fromPath).resolve(specifier);
}

function resolvePgCloudflareWorkerdEntry(fromPath: string): string {
  const packageJsonPath = createPgPackageRequire(fromPath).resolve('pg-cloudflare/package.json');
  return join(dirname(packageJsonPath), 'dist', 'index.js');
}

// pg requires `fs` only to read sslcert/sslkey/sslrootcert files, which a Worker cannot read.
// workerd has node:fs only from compatibility date 2025-09-15, and this module loads at Worker
// start, so that require stays unsupported and throws only if it runs.
function pgWorkerRequireShim(bundle: string): string {
  return [
    'import * as __voidNodeCrypto from "node:crypto";',
    'import * as __voidNodeDns from "node:dns";',
    'import * as __voidNodeEvents from "node:events";',
    'import * as __voidNodeNet from "node:net";',
    'import * as __voidNodeTls from "node:tls";',
    'import * as __voidNodeUtil from "node:util";',
    'import * as __voidNodeUtilTypes from "node:util/types";',
    'var __voidNodeRequireModules = {',
    '  crypto: __voidNodeCrypto,',
    '  dns: __voidNodeDns,',
    '  events: __voidNodeEvents,',
    '  net: __voidNodeNet,',
    '  tls: __voidNodeTls,',
    '  util: __voidNodeUtil,',
    '  "util/types": __voidNodeUtilTypes,',
    '};',
    'var __require = (id) => {',
    '  if (id.startsWith("node:")) id = id.slice(5);',
    '  const mod = __voidNodeRequireModules[id];',
    '  if (mod) return mod;',
    `  throw new Error(\`Unsupported require("\${id}") in Void PG ${bundle}\`);`,
    '};',
  ].join('\n');
}

// The Node built-ins that mysql2 and its bundled dependencies require. Each one is the
// module's default export, which matches CommonJS `module.exports`: safer-buffer calls
// `hasOwnProperty` on `require("buffer")`, and an ESM namespace object has no prototype.
// mysql2 wraps its optional `cardinal` require in try/catch, so it stays unsupported.
function mysqlWorkerRequireShim(bundle: string): string {
  return [
    'import __voidNodeBuffer from "node:buffer";',
    'import __voidNodeCrypto from "node:crypto";',
    'import __voidNodeDiagnosticsChannel from "node:diagnostics_channel";',
    'import __voidNodeEvents from "node:events";',
    'import __voidNodeNet from "node:net";',
    'import __voidNodeProcess from "node:process";',
    'import __voidNodeStream from "node:stream";',
    'import __voidNodeStringDecoder from "node:string_decoder";',
    'import __voidNodeTimers from "node:timers";',
    'import __voidNodeTls from "node:tls";',
    'import __voidNodeUrl from "node:url";',
    'import __voidNodeUtil from "node:util";',
    'import __voidNodeZlib from "node:zlib";',
    'var __voidNodeRequireModules = {',
    '  buffer: __voidNodeBuffer,',
    '  crypto: __voidNodeCrypto,',
    '  diagnostics_channel: __voidNodeDiagnosticsChannel,',
    '  events: __voidNodeEvents,',
    '  net: __voidNodeNet,',
    '  process: __voidNodeProcess,',
    '  stream: __voidNodeStream,',
    '  string_decoder: __voidNodeStringDecoder,',
    '  timers: __voidNodeTimers,',
    '  tls: __voidNodeTls,',
    '  url: __voidNodeUrl,',
    '  util: __voidNodeUtil,',
    '  zlib: __voidNodeZlib,',
    '};',
    'var __require = (id) => {',
    '  if (id.startsWith("node:")) id = id.slice(5);',
    '  const mod = __voidNodeRequireModules[id];',
    '  if (mod) return mod;',
    `  throw new Error(\`Unsupported require("\${id}") in Void MySQL ${bundle}\`);`,
    '};',
  ].join('\n');
}

/**
 * Bundle a worker entry into a self-contained module.
 *
 * Used for frameworks whose build output has unbundled bare imports
 * (e.g. SvelteKit's `_worker.js` imports from `@sveltejs/kit`).
 */
export async function bundleEntry(root: string, entry: string): Promise<WrapperResult> {
  const tmpDir = join(root, '.void', 'bundle');
  mkdirSync(tmpDir, { recursive: true });
  const outDir = join(tmpDir, 'out');
  await build({
    root: tmpDir,
    logLevel: 'silent',
    build: {
      outDir,
      emptyOutDir: true,
      lib: {
        entry,
        formats: ['es'],
        fileName: 'index',
      },
      rollupOptions: {
        external: [/^cloudflare:/, /^node:/],
        output: {
          // Workers for Platforms restricts caches.default access.
          // Stub it so framework code (e.g. SvelteKit) that uses it doesn't throw.
          banner: [
            'const __noopCache = {',
            '  match() { return Promise.resolve(undefined); },',
            '  put() { return Promise.resolve(); },',
            '  delete() { return Promise.resolve(false); },',
            '};',
            'globalThis.caches = { default: __noopCache, open() { return Promise.resolve(__noopCache); } };',
          ].join('\n'),
        },
      },
      minify: false,
      target: 'esnext',
    },
  });

  // Read actual entry filename from the output directory. Vite/Rollup can also
  // emit sibling chunks like index-server-*.js, and readdir order is
  // filesystem-dependent.
  const entryFilename = selectBundledEntryFilename(readdirSync(outDir));

  return { entryFilename, outputDir: outDir };
}

/** Clean up the temporary directories created while generating a deploy wrapper. */
export function cleanupWrapper(root: string): void {
  const voidDir = join(root, '.void');
  for (const directory of ['handlers', 'migration-handler', 'isr', 'bundle']) {
    rmSync(join(voidDir, directory), { recursive: true, force: true });
  }
}

// ─── Source Generators ─────────────────────────────────────────────

function generateWrapperSource(
  renamedEntry: string,
  handlersModule: string,
  features: WrapperFeatures,
  migrations?: Array<{ name: string; sql: string }>,
  migrationPlanBundle?: MigrationPlanBundle,
): string {
  const lines: Array<string> = [];
  lines.push(WRAPPER_MARKER);
  lines.push(`import original from "./${renamedEntry}";`);
  // Durable Object, Workflow and entrypoint classes must stay exported from the uploaded module.
  lines.push(`export * from "./${renamedEntry}";`);

  if (features.isr) {
    lines.push('import { handleFrameworkIsr } from "./__void_isr.mjs";');
    lines.push(`const __voidIsrDeploymentId = ${JSON.stringify(crypto.randomUUID())};`);
    lines.push(
      `const __voidIsrPolicy = ${JSON.stringify({
        revalidate: features.isr.revalidate,
        queryAllowlist: features.isr.queryAllowlist,
      })};`,
    );
  }

  if (features.crons.length > 0) {
    lines.push(`import { handleScheduled } from "./${handlersModule}";`);
  }
  if (features.queues.length > 0) {
    lines.push(`import { handleQueue, handleQueueRelay } from "./${handlersModule}";`);
  }
  if (migrations && migrations.length > 0) {
    lines.push(`import { createMigrationHandler } from "./__void_migration_handler.mjs";`);
    lines.push(`const __migrations = ${JSON.stringify(migrations)};`);
    lines.push(`const __migrationPlanBundle = ${JSON.stringify(migrationPlanBundle)};`);
  }

  lines.push('');

  // Wrap fetch if any intercepted routes are needed
  const needsFetchWrap =
    features.readiness ||
    features.crons.length > 0 ||
    features.queues.length > 0 ||
    (migrations && migrations.length > 0) ||
    !!features.isr;

  if (needsFetchWrap) {
    lines.push('async function wrappedFetch(request, env, ctx) {');
    lines.push('  const url = new URL(request.url);');
    if (features.isr) {
      lines.push('  env.__VOID_ISR_DEPLOYMENT_ID ??= __voidIsrDeploymentId;');
      lines.push('  env.__VOID_ISR_HOST = url.hostname;');
    }

    // Readiness probe — platform polls this to confirm the worker is live
    // after WfP upload. Handled here (before original.fetch) so the user's
    // framework handler doesn't route it to env.ASSETS, which returns CF's
    // "Assets have not yet been deployed" stub during asset propagation
    // and would trip the platform's probe.
    if (
      features.readiness ||
      features.crons.length > 0 ||
      features.queues.length > 0 ||
      features.hasMigrations
    ) {
      lines.push('  if (request.method === "GET" && url.pathname === "/__void/ready") {');
      // An entry without a `fetch` handler (e.g. a framework build whose
      // entry is a bare function) would fail every app request, so it must
      // not pass the probe and get promoted.
      lines.push('    if (typeof original?.fetch !== "function") {');
      lines.push(
        '      return Response.json({ ready: false, error: "worker entry has no fetch handler" }, { status: 503, headers: { "cache-control": "no-store" } });',
      );
      lines.push('    }');
      lines.push(
        `    return Response.json({ ready: true${features.versionMetadataBinding ? `, versionId: env[${JSON.stringify(features.versionMetadataBinding)}]?.id` : ''} }${features.versionMetadataBinding ? ', { headers: { "cache-control": "no-store" } }' : ''});`,
      );
      lines.push('  }');
    }

    if (features.queues.length > 0) {
      lines.push('  if (request.method === "POST" && url.pathname === "/__void/queue") {');
      lines.push('    const expected = env?.__VOID_PROXY_TOKEN;');
      lines.push('    if (!expected || request.headers.get("x-void-internal") !== expected) {');
      lines.push('      return Response.json({ error: "unauthorized" }, { status: 401 });');
      lines.push('    }');
      lines.push('    try {');
      lines.push(
        '      return Response.json(await handleQueueRelay(await request.json(), env, ctx));',
      );
      lines.push('    } catch {');
      lines.push(
        '      return Response.json({ error: "Invalid queue payload" }, { status: 400 });',
      );
      lines.push('    }');
      lines.push('  }');
    }

    // Migration handler
    if (migrations && migrations.length > 0) {
      lines.push('  if (request.method === "POST" && url.pathname === "/__void/migrate") {');
      lines.push('    const handler = createMigrationHandler(env, __migrations);');
      lines.push('    return handler(request);');
      lines.push('  }');
      lines.push(
        '  if (request.method === "GET" && url.pathname === "/__void/migrate/capabilities") {',
      );
      lines.push(
        '    const handler = createMigrationHandler(env, __migrations, undefined, __migrationPlanBundle);',
      );
      lines.push('    return handler(request);');
      lines.push('  }');
      lines.push('  if (request.method === "POST" && url.pathname === "/__void/migrate/app") {');
      lines.push(
        '    const handler = createMigrationHandler(env, __migrations, undefined, __migrationPlanBundle);',
      );
      lines.push('    return handler(request);');
      lines.push('  }');
      lines.push(
        '  if (request.method === "GET" && url.pathname.startsWith("/__void/migrate/app/attempt/")) {',
      );
      lines.push(
        '    const handler = createMigrationHandler(env, __migrations, undefined, __migrationPlanBundle);',
      );
      lines.push('    return handler(request);');
      lines.push('  }');
    }

    // Cron handler
    if (features.crons.length > 0) {
      lines.push('  if (request.method === "POST" && url.pathname === "/__void/scheduled") {');
      lines.push('    const __token = request.headers.get("x-void-internal");');
      lines.push('    const __expected = env?.__VOID_PROXY_TOKEN || env?.CRON_SECRET;');
      lines.push('    if (!__expected || __token !== __expected) {');
      lines.push("      return new Response(JSON.stringify({ error: 'unauthorized' }), {");
      lines.push('        status: 401,');
      lines.push('        headers: { "Content-Type": "application/json" },');
      lines.push('      });');
      lines.push('    }');
      lines.push('    try {');
      lines.push('      const { cron, scheduledTime } = await request.json();');
      lines.push('      const controller = { cron, scheduledTime, noRetry() {} };');
      lines.push('      await handleScheduled(controller, env, ctx);');
      lines.push('      return new Response(JSON.stringify({ ok: true }), {');
      lines.push('        headers: { "Content-Type": "application/json" },');
      lines.push('      });');
      lines.push('    } catch (err) {');
      lines.push('      return new Response(JSON.stringify({ error: String(err) }), {');
      lines.push('        status: 500,');
      lines.push('        headers: { "Content-Type": "application/json" },');
      lines.push('      });');
      lines.push('    }');
      lines.push('  }');
    }

    if (features.isr) {
      lines.push(
        '  if (env.ISR_CACHE && request.headers.get("upgrade")?.toLowerCase() !== "websocket") {',
      );
      lines.push(
        '    const cached = await handleFrameworkIsr(request, env, ctx, { ...__voidIsrPolicy, deploymentId: __voidIsrDeploymentId }, (req) => original.fetch(req, env, ctx));',
      );
      lines.push('    if (cached) return cached;');
      lines.push('  }');
    }
    lines.push('  return original.fetch(request, env, ctx);');
    lines.push('}');
    lines.push('');
  }

  lines.push('export default {');
  // Keep the entry's own handlers, such as email or tail; Void's handlers below take precedence.
  lines.push('  ...original,');

  if (needsFetchWrap) {
    lines.push('  fetch: wrappedFetch,');
  } else {
    lines.push('  fetch: original.fetch,');
  }

  if (features.crons.length > 0) {
    lines.push(
      features.isr
        ? '  scheduled(controller, env, ctx) { env.__VOID_ISR_DEPLOYMENT_ID ??= __voidIsrDeploymentId; return handleScheduled(controller, env, ctx); },'
        : '  scheduled: handleScheduled,',
    );
  }

  if (features.queues.length > 0) {
    lines.push(
      features.isr
        ? '  queue(batch, env, ctx) { env.__VOID_ISR_DEPLOYMENT_ID ??= __voidIsrDeploymentId; return handleQueue(batch, env, ctx); },'
        : '  queue: handleQueue,',
    );
  }

  lines.push('};');

  return lines.join('\n');
}

function generateHandlersSource(
  root: string,
  features: WrapperFeatures,
  dialect: DatabaseDialect,
): string {
  const lines: Array<string> = [];
  const paths = readProjectPaths(root);
  // PostgreSQL and MySQL jobs run each event in Void's request scope, as a Void app's do, so
  // void/db keeps one pool for the event instead of opening one for each query. D1 jobs keep
  // their reads on the primary: in a request scope, void/db reads D1 through a replica-capable
  // session.
  const scoped = dialect !== 'sqlite';
  if (scoped) {
    lines.push(`import { withRuntimeEnv } from ${JSON.stringify(envModuleFile)};`);
  }

  // Scheduled handlers
  if (features.crons.length > 0) {
    for (let i = 0; i < features.crons.length; i++) {
      const absPath = join(paths.cronsDir, features.crons[i].filePath);
      lines.push(`import cronHandler${i} from "${absPath}";`);
    }

    lines.push('');
    lines.push(
      scoped
        ? 'async function __runScheduled(controller, env, ctx) {'
        : 'export async function handleScheduled(controller, env, ctx) {',
    );
    lines.push('  const tasks = [];');
    for (let i = 0; i < features.crons.length; i++) {
      lines.push(`  if (${JSON.stringify(features.crons[i].crons)}.includes(controller.cron)) {`);
      lines.push('    tasks.push((async () => {');
      lines.push(`      if (typeof cronHandler${i} === "function") {`);
      lines.push(`        await cronHandler${i}(controller, env, ctx);`);
      lines.push(
        `      } else if (cronHandler${i} && typeof cronHandler${i}.default === "function") {`,
      );
      lines.push(`        await cronHandler${i}.default(controller, env, ctx);`);
      lines.push('      }');
      lines.push('    })());');
      lines.push('  }');
    }
    lines.push('  const results = await Promise.allSettled(tasks);');
    lines.push(
      '  const errors = results.filter(result => result.status === "rejected").map(result => result.reason);',
    );
    lines.push('  if (errors.length) throw new AggregateError(errors, "Scheduled jobs failed");');
    lines.push('}');
    if (scoped) {
      lines.push('export function handleScheduled(controller, env, ctx) {');
      lines.push('  return withRuntimeEnv(env, () => __runScheduled(controller, env, ctx));');
      lines.push('}');
    }
  }

  // Queue handlers
  if (features.queues.length > 0) {
    lines.push('');
    for (let i = 0; i < features.queues.length; i++) {
      const absPath = join(paths.queuesDir, features.queues[i].filePath);
      lines.push(`import queueHandler${i} from "${absPath}";`);
    }

    lines.push('');
    lines.push(generateQueueResolverSource(features.queues.map((queue) => queue.name)));
    lines.push('');
    lines.push(
      scoped
        ? 'async function __runQueue(batch, env, ctx) {'
        : 'export async function handleQueue(batch, env, ctx) {',
    );
    lines.push('  const queueSuffix = batch.queue;');
    lines.push('  const __queueIndex = __resolveQueueIndex(queueSuffix);');
    lines.push('  if (__queueIndex === -1) {');
    lines.push('    batch.retryAll();');
    lines.push(
      '    throw new Error(`No unambiguous queue handler matches "${String(queueSuffix)}"`);',
    );
    lines.push('  }');
    lines.push('  switch (__queueIndex) {');
    for (let i = 0; i < features.queues.length; i++) {
      lines.push(`    case ${i}:`);
      lines.push(`      if (typeof queueHandler${i} === "function") {`);
      lines.push(`        await queueHandler${i}(batch, env);`);
      lines.push(
        `      } else if (queueHandler${i} && typeof queueHandler${i}.default === "function") {`,
      );
      lines.push(`        await queueHandler${i}.default(batch, env);`);
      lines.push(`      }`);
      lines.push(`      return;`);
    }
    lines.push('  }');
    lines.push('}');
    if (scoped) {
      lines.push('export function handleQueue(batch, env, ctx) {');
      lines.push('  return withRuntimeEnv(env, () => __runQueue(batch, env, ctx));');
      lines.push('}');
    }
    lines.push(`
export async function handleQueueRelay(payload, env, ctx) {
  if (!payload || typeof payload.queue !== "string" || !Array.isArray(payload.messages) ||
    payload.messages.some(m => !m || typeof m.id !== "string" || typeof m.timestamp !== "string" || !Number.isFinite(Date.parse(m.timestamp)))) {
    throw new Error("Invalid queue payload");
  }
  const decisions = new Map();
  const messages = payload.messages.map(m => {
    const decide = (decision) => { if (!decisions.has(m.id)) decisions.set(m.id, decision); };
    return {
      id: m.id, timestamp: new Date(m.timestamp), body: m.body, attempts: m.attempts,
      ack() { decide({ action: "ack" }); },
      retry(options) { decide({ action: "retry", ...(options?.delaySeconds != null ? { delaySeconds: options.delaySeconds } : {}) }); },
    };
  });
  const batch = {
    queue: payload.queue, messages,
    ackAll() { for (const message of messages) message.ack(); },
    retryAll(options) { for (const message of messages) message.retry(options); },
  };
  let ok = true;
  try { await handleQueue(batch, env, ctx); } catch { ok = false; }
  return { ok, ...(decisions.size ? { decisions: Object.fromEntries(decisions) } : {}) };
}`);
  }

  return lines.join('\n');
}
