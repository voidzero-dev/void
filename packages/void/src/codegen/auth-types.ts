import { existsSync, rmSync } from 'node:fs';
import { join, relative } from 'pathslash';
import { writeFileIfChanged } from './write-if-changed.ts';

export type AuthTypesResult = {
  dts: string;
};

/**
 * Generate `.void/auth.d.ts` content. Fills `void/auth`'s `VoidAuthTypes`
 * registry with Better Auth inference from the app's `defineAuth` config
 * (plugins, `user.additionalFields`, etc.), which `AuthUser` and `AuthSession`
 * read from.
 *
 * Uses `typeof import(...)` on the auth config file so TypeScript handles the
 * inference — codegen never analyses types itself. `better-auth` is reached
 * through `void/auth`'s `InferAuthSession`, because apps usually do not depend
 * on `better-auth` directly and could not resolve it from `.void/`.
 *
 * @param authFileAbs Absolute path to the user's auth config file.
 * @param outDir Absolute path to the project's `.void/` directory.
 */
export function generateAuthTypes(authFileAbs: string, outDir: string): AuthTypesResult {
  const importPath = relative(outDir, authFileAbs);
  const lines: Array<string> = [];

  lines.push('// Auto-generated by void — do not edit');
  lines.push('export {}');
  lines.push('');
  lines.push('import type { InferAuthSession } from "void/auth";');
  lines.push('');
  lines.push(
    `type _VoidAuthSession = InferAuthSession<typeof import("${importPath}")["default"]>;`,
  );
  lines.push('');
  lines.push('declare module "void/auth" {');
  lines.push('  interface VoidAuthTypes {');
  lines.push('    user: _VoidAuthSession["user"];');
  lines.push('    session: _VoidAuthSession["session"];');
  lines.push('  }');
  lines.push('}');
  lines.push('');

  return { dts: lines.join('\n') };
}

export function authTypesPath(outDir: string): string {
  return join(outDir, 'auth.d.ts');
}

/** Remove `.void/auth.d.ts` when auth is disabled or the config file is gone. */
export function removeAuthTypesIfPresent(outDir: string): boolean {
  const filePath = authTypesPath(outDir);
  if (!existsSync(filePath)) {
    return false;
  }
  rmSync(filePath, { force: true });
  return true;
}

/**
 * Write or remove `.void/auth.d.ts` from the current auth config path.
 * Returns whether the file on disk changed.
 */
export function syncAuthTypesFile(authConfigPath: string | null, outDir: string): boolean {
  if (!authConfigPath) {
    return removeAuthTypesIfPresent(outDir);
  }
  const { dts } = generateAuthTypes(authConfigPath, outDir);
  return writeFileIfChanged(authTypesPath(outDir), dts);
}
