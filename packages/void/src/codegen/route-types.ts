import { relative } from 'pathslash';
import type { PageDefinition } from '../pages/types.ts';
import type { RouteDefinition } from '../router/parse-filename.ts';
import type { ScanResult } from '../router/scan.ts';
import type { WebSocketRouteDefinition } from '../router/websocket.ts';

export type RouteTypesResult = {
  dts: string;
};

/** Present bracket parameters without changing the router's compiled patterns. */
function publicRoutePattern(pattern: string): string {
  return pattern
    .split('/')
    .map((segment) => {
      if (segment === '*') {
        return '[...]';
      }
      const param = segment.match(/^:([^/{}]+)(\{\.\+\})?$/);
      return param ? `[${param[2] ? '...' : ''}${param[1]}]` : segment;
    })
    .join('/');
}

/** Legacy keys stay indexable and carry the exact same contract as the public key. */
function legacyRouteAlias(lines: Array<string>, map: string, pattern: string): void {
  const publicPattern = publicRoutePattern(pattern);
  if (publicPattern !== pattern) {
    // Escape comment delimiters in static segments before writing JSDoc.
    const label = JSON.stringify(publicPattern).replaceAll('*/', String.raw`*\/`);
    lines.push(
      `    /** @deprecated Use ${label} instead. */`,
      `    ${JSON.stringify(pattern)}: ${map}[${JSON.stringify(publicPattern)}];`,
    );
  }
}

/** Percent-encode a pattern's fixed segments the way `routeUrl()` serializes its pathname. */
function encodeRoutePattern(pattern: string): string {
  return pattern
    .split('/')
    .map((segment) => {
      if (segment.startsWith(':') || segment === '*' || /^\[.*\]$/.test(segment)) {
        return segment;
      }
      const url = new URL('https://void.invalid');
      url.pathname = `/${segment}`;
      return url.pathname.slice(1);
    })
    .join('/');
}

/**
 * One PageQueryMap entry per page whose loader could validate its query.
 *
 * The schema is read from the page server's exported `query` value, not from
 * the loader. A page server reaches `void/routes` through `void`, so reading
 * the loader's inferred type from there would make it refer to itself and
 * TypeScript would infer `any` for the handler. A schema value has no such
 * dependency.
 *
 * A `.dev` + `.prod` pair shares one pattern, so its two pages become a union.
 */
function pageQueryEntry(importPath: string): Array<string> {
  const module = `typeof import(${JSON.stringify(importPath)})`;
  return [
    `      input: PageQueryInputFallback<PageQueryInputOf<PageQuerySchema<${module}>>>;`,
    `      output: PageQueryOutputFallback<PageQueryOutputOf<PageQuerySchema<PageQueryPublished<${module}>>>>;`,
  ];
}

function pageQueryLines(
  pages: Array<PageDefinition>,
  pagesDir: string | undefined,
  outDir: string,
): Array<string> {
  if (!pagesDir) {
    return [];
  }
  const typedPatterns = new Set(
    pages.flatMap((page) =>
      page.serverPath !== null && page.methods.includes('loader') ? [page.pattern] : [],
    ),
  );
  if (typedPatterns.size === 0) {
    return [];
  }

  const entriesByPattern = new Map<string, Array<Array<string>>>();
  for (const page of pages) {
    if (!typedPatterns.has(page.pattern)) {
      continue;
    }
    // A side of a `.dev` + `.prod` pair without a loader validates nothing.
    const entry =
      page.serverPath !== null && page.methods.includes('loader')
        ? pageQueryEntry(relative(outDir, `${pagesDir}/${page.serverPath}`))
        : ['      input: RouteQuery;', '      output: Record<string, string | Array<string>>;'];
    const entries = entriesByPattern.get(page.pattern);
    if (entries) {
      entries.push(entry);
    } else {
      entriesByPattern.set(page.pattern, [entry]);
    }
  }

  const lines: Array<string> = ['  export interface PageQueryMap {'];
  for (const [pattern, entries] of entriesByPattern) {
    lines.push(`    ${JSON.stringify(publicRoutePattern(pattern))}: {`);
    entries.forEach((entry, index) => {
      if (index > 0) {
        lines.push('    } | {');
      }
      lines.push(...entry);
    });
    lines.push('    };');
    legacyRouteAlias(lines, 'PageQueryMap', pattern);
  }
  lines.push('  }');
  return lines;
}

/**
 * Generate .void/routes.d.ts content.
 *
 * Uses `typeof import(...)` so TypeScript resolves all types.
 * The codegen generates scaffolding only — never analyzes types itself.
 */
export function generateRouteTypes(
  scan: ScanResult,
  routesDir: string,
  outDir: string,
  pagesDir?: string,
  options: { typedRoutes?: boolean } = {},
): RouteTypesResult {
  const lines: Array<string> = [];

  lines.push(
    '// Auto-generated by void — do not edit',
    // Top-level export makes this a module so `declare module` below is an
    // augmentation (merges with the real void/routes) rather than an ambient
    // module declaration (which would replace it and hide exported types).
    'export {}',
    // Inline the Standard Schema types so the generated file is self-contained
    // (no external dependency on @standard-schema/spec)
    'type StandardSchemaV1<Input = unknown, Output = Input> = {',
    '  readonly "~standard": {',
    '    readonly version: 1;',
    '    readonly vendor: string;',
    '    readonly validate: (value: unknown) => unknown;',
    '    readonly types?: { readonly input: Input; readonly output: Output } | undefined;',
    '  };',
    '};',
    'declare namespace StandardSchemaV1 {',
    '  type InferInput<Schema extends StandardSchemaV1> = NonNullable<',
    '    Schema["~standard"]["types"]',
    '  >["input"];',
    '  type InferOutput<Schema extends StandardSchemaV1> = NonNullable<',
    '    Schema["~standard"]["types"]',
    '  >["output"];',
    '}',
    '',
    // JSON keeps invalid array positions as null, but omits the same values in objects.
    // Find optional object keys before Serialize removes their omitted-value union members.
    'type JsonOmitted = undefined | Function | symbol;',
    'type SerializeArrayElement<T> = T extends JsonOmitted ? null : Serialize<T>;',
    // A homomorphic map preserves ordinary arrays and tuples, but maps methods too
    // on array intersections (e.g. Zod brands). Rebuild those as JSON arrays.
    'type SerializeArray<T extends readonly unknown[]> =',
    '  { [K in keyof T]: SerializeArrayElement<T[K]> } extends infer A',
    '    ? A extends readonly unknown[] ? A',
    '      : T extends unknown[] ? Array<SerializeArrayElement<T[number]>>',
    '      : ReadonlyArray<SerializeArrayElement<T[number]>>',
    '    : never;',
    'type JsonOptionalKeys<T> = {',
    '  [K in keyof T]-?: Extract<T[K], JsonOmitted> extends never ? never : K;',
    '}[keyof T];',
    'type SerializeObject<T> = {',
    '  [K in keyof T as K extends symbol ? never : T[K] extends JsonOmitted ? never : K]: Serialize<T[K]>;',
    '};',
    '',
    'type Serialize<T> =',
    '  T extends Response ? never :',
    '  T extends Date ? string :',
    '  T extends bigint ? never :',
    '  T extends JsonOmitted ? never :',
    '  T extends readonly unknown[] ? SerializeArray<T> :',
    '  T extends object ? SerializeObject<Omit<T, JsonOptionalKeys<T>> & Partial<Pick<T, JsonOptionalKeys<T>>>> :',
    '  T;',
    '',
    // Helper type to extract validated input from __validators
    'type ExtractInput<V> = {',
    '  [K in keyof V as V[K] extends StandardSchemaV1 ? K : never]:',
    '    V[K] extends StandardSchemaV1 ? StandardSchemaV1.InferInput<V[K]> : never;',
    '};',
    '',
    'type ExtractOutput<S> =',
    '  S extends StandardSchemaV1 ? StandardSchemaV1.InferOutput<S> : never;',
    '',
    'type RouteParams<P extends readonly string[]> =',
    '  P extends readonly [] ? Record<string, never> : { [K in P[number]]: string };',
    '',
    'declare module "void/routes" {',
    '  export interface RouteMap {}',
    '  export interface WebSocketRouteMap {}',
    '  export interface PageActionMap {}',
    '',
    // Projects resolve void/routes to this generated declaration through their
    // tsconfig paths, so keep the standalone helper's declarations here as well.
    '  export type RoutePath = keyof RoutePathMap & string;',
    '  export type RouteQueryValue = string | number | boolean | null | undefined;',
    '  export type RouteQuery = Record<string, RouteQueryValue | ReadonlyArray<RouteQueryValue>>;',
    // A page's exported `query` schema, or never when it exports none.
    '  type PageQuerySchema<M> = M extends { query: infer S } ? Extract<S, StandardSchemaV1> : never;',
    // A query string carries text, so an input that is not a URL primitive (a
    // Date, a class instance) is passed as a string. An `unknown` input, such
    // as Zod 4's `z.coerce.number()`, takes any URL value. Arrays map per item.
    '  type RouteQueryItemOf<T> = unknown extends T ? RouteQueryValue : T extends RouteQueryValue ? T : string;',
    '  type RouteQueryValueOf<T> = unknown extends T',
    '    ? RouteQueryValue | ReadonlyArray<RouteQueryValue>',
    '    : T extends ReadonlyArray<infer E> ? ReadonlyArray<RouteQueryItemOf<E>> : RouteQueryItemOf<T>;',
    '  type PageQueryInputOf<S> = S extends StandardSchemaV1',
    '    ? { [K in keyof StandardSchemaV1.InferInput<S>]: RouteQueryValueOf<StandardSchemaV1.InferInput<S>[K]> }',
    '    : never;',
    '  type PageQueryOutputOf<S> = S extends StandardSchemaV1 ? StandardSchemaV1.InferOutput<S> : never;',
    // A page publishes its validated query only when it sets the flag, so the
    // read type follows the same opt-in the payload does.
    '  type PageQueryPublished<M> = M extends { exposeQuery: true } ? M : never;',
    // A `.dev` + `.prod` pair shares one key, so a side without a schema has to
    // keep accepting anything instead of vanishing into the union.
    '  type PageQueryInputFallback<T> = [T] extends [never] ? RouteQuery : T;',
    '  type PageQueryOutputFallback<T> = [T] extends [never] ? Record<string, string | Array<string>> : T;',
    '  type RouteQueryOptions<P> = P extends keyof PageQueryMap',
    "    ? [PageQueryMap[P]['input']] extends [never]",
    '      ? { query?: RouteQuery }',
    "      : {} extends PageQueryMap[P]['input']",
    "        ? { query?: PageQueryMap[P]['input'] }",
    "        : { query: PageQueryMap[P]['input'] }",
    '    : { query?: RouteQuery };',
    '  export type RouteOptions<P extends RoutePath> = {',
    '    hash?: string;',
    '  } & RouteQueryOptions<P> & ([RoutePathMap[P]] extends [never]',
    '    ? { params?: never }',
    '    : { params: { [K in RoutePathMap[P] & string]: string | number } });',
    '  export type RouteUrlArgs<P extends RoutePath> = {} extends RouteOptions<P>',
    '    ? [options?: RouteOptions<P>]',
    '    : [options: RouteOptions<P>];',
    '  export type RouteDestination<P extends RoutePath = RoutePath> = P extends RoutePath',
    '    ? { pathname: P } & RouteOptions<P>',
    '    : never;',
    '  type RouteUrlSegment<S extends string> = S extends `:${string}` | `[${string}]` | "*" ? string : S;',
    '  type CheckedRoutePath<P extends string> = P extends `/${infer Segment}/${infer Rest}`',
    '    ? Rest extends ""',
    '      ? string extends RouteUrlSegment<Segment> ? never : P',
    '      : P',
    '    : P extends `/${infer Segment}`',
    '      ? string extends RouteUrlSegment<Segment> ? never : P',
    '      : P;',
    '  type RouteSegmentsUrl<P extends string> = P extends `${infer Segment}/${infer Rest}`',
    '    ? `${RouteUrlSegment<Segment>}/${RouteSegmentsUrl<Rest>}`',
    '    : RouteUrlSegment<P>;',
    '  type RoutePatternUrl<P extends string> = P extends `${infer Prefix}/${"*" | "[...]"}/`',
    '    ? `${RouteSegmentsUrl<Prefix>}/` | `${RouteSegmentsUrl<Prefix>}/${string}/`',
    '    : P extends `${infer Prefix}/${"*" | "[...]"}`',
    '    ? (Prefix extends "" ? "/" : RouteSegmentsUrl<Prefix>) | `${RouteSegmentsUrl<Prefix>}/${string}`',
    '    : RouteSegmentsUrl<P>;',
    '  type EncodedRoutePath = EncodedRoutePathMap[keyof EncodedRoutePathMap] & string;',
    '  type RoutePathUrl = RoutePatternUrl<CheckedRoutePath<RoutePath | EncodedRoutePath>>;',
    '  type BuiltRouteUrl = string & { readonly __voidRouteUrl: true };',
    '  type RouteUrlBase = BuiltRouteUrl | RoutePathUrl;',
    '  type TypedRoutes = RouteTypesConfig extends { typedRoutes: true } ? true : false;',
    '  export type RouteUrl = TypedRoutes extends true',
    '    ? RouteUrlBase | `${RouteUrlBase}${"?" | "#"}${string}`',
    '    : string;',
    '  export type Href = TypedRoutes extends true',
    '    ? RouteUrl | `${"?" | "#"}${string}` | `${"http://" | "https://" | "mailto:" | "tel:"}${string}`',
    '    : string;',
    '  export type RouteUrlInput = Href | URL | RouteDestination;',
    '  export function routeUrl<P extends RoutePath>(',
    '    path: P,',
    '    ...args: RouteUrlArgs<P>',
    '  ): RouteUrl;',
    '',
    '  export interface RouteTypesConfig {',
  );
  if (options.typedRoutes) {
    lines.push('    typedRoutes: true;');
  }
  lines.push('  }', '', '  export interface RoutePathMap {');
  const paths = new Map<string, Set<string>>();
  // A route file without HTTP method exports serves every method through its default export.
  for (const route of [...scan.routes, ...scan.pages.pages, ...(scan.websockets ?? [])]) {
    const params = paths.get(route.pattern) ?? new Set<string>();
    for (const name of route.params) {
      params.add(name);
    }
    if (route.pattern.split('/').includes('*')) {
      params.add('*');
    }
    paths.set(route.pattern, params);
  }
  for (const [pattern, params] of paths) {
    const names = [...params].map((name) => JSON.stringify(name)).join(' | ') || 'never';
    lines.push(`    ${JSON.stringify(publicRoutePattern(pattern))}: ${names};`);
    legacyRouteAlias(lines, 'RoutePathMap', pattern);
  }
  lines.push('  }', '', '  export interface PagePathMap {');
  // A .dev + .prod page pair shares one pattern and its params.
  const pagePaths = new Map<string, Set<string>>();
  for (const page of scan.pages.pages) {
    const params = pagePaths.get(page.pattern) ?? new Set<string>();
    for (const name of page.params) {
      params.add(name);
    }
    if (page.pattern.split('/').includes('*')) {
      params.add('*');
    }
    pagePaths.set(page.pattern, params);
  }
  for (const [pattern, params] of pagePaths) {
    const names = [...params].map((name) => JSON.stringify(name)).join(' | ') || 'never';
    lines.push(`    ${JSON.stringify(publicRoutePattern(pattern))}: ${names};`);
    legacyRouteAlias(lines, 'PagePathMap', pattern);
  }
  lines.push(
    '  }',
    '  export type PagePath = keyof PagePathMap & string;',
    '  export type PageParams<P extends PagePath> = P extends PagePath',
    '    ? { [K in Exclude<PagePathMap[P], "*"> & string]: string }',
    '    : never;',
    '',
    '  export interface PageQueryMap {}',
    '  export type PageQueryInput<P> = P extends keyof PageQueryMap',
    "    ? [PageQueryMap[P]['input']] extends [never]",
    '      ? RouteQuery',
    "      : PageQueryMap[P]['input']",
    '    : RouteQuery;',
    '  export type PageQuery<P> = P extends keyof PageQueryMap',
    "    ? [PageQueryMap[P]['output']] extends [never]",
    '      ? Record<string, string | Array<string>>',
    "      : PageQueryMap[P]['output']",
    '    : Record<string, string | Array<string>>;',
    '',
    ...pageQueryLines(scan.pages.pages, pagesDir, outDir),
    '',
    // `routeUrl()` returns `/caf%C3%A9%20menu` for `/café menu`, so accept that spelling too.
    '  export interface EncodedRoutePathMap {',
  );
  for (const pattern of paths.keys()) {
    const publicPattern = publicRoutePattern(pattern);
    const encoded = encodeRoutePattern(publicPattern);
    if (encoded !== publicPattern) {
      lines.push(`    ${JSON.stringify(publicPattern)}: ${JSON.stringify(encoded)};`);
      // Preserve the original encoded map's keys and values too.
      if (publicPattern !== pattern) {
        lines.push(
          `    ${JSON.stringify(pattern)}: ${JSON.stringify(encodeRoutePattern(pattern))};`,
        );
      }
    }
  }
  lines.push(
    '  }',
    '',
    '  /** Union of known route patterns (keys of the generated RouteMap). */',
    '  export type RouteName = keyof RouteMap;',
    '',
    '  /**',
    '   * Destination type for rewrites / fallbacks / c.rewrite().',
    '   *',
    '   * The `string & {}` branch keeps IDE autocomplete of known routes while',
    '   * still accepting arbitrary strings (needed for dynamic paths like',
    '   * `/users/${id}`). When no routes are generated yet, `RouteName` is',
    '   * `never` and this degenerates to `string & {}`, which is assignable',
    '   * from any string.',
    '   */',
    '  export type RewriteDestination = RouteName | (string & {});',
    '',
    '  export type ParseActionUrl<U extends string> = U extends `${infer Base}?${infer Action}` ? {',
    '    base: Base;',
    '    action: Action extends `${infer Name}&${string}` ? Name : Action;',
    '  } : {',
    '    base: U;',
    '    action: never;',
    '  };',
    '',
    // A .dev + .prod page pair is a union of two page shapes. A type parameter
    // makes these helpers read each shape on its own, as in void/routes.
    '  type PageActionBody<P> = [Extract<P, { body: unknown }>] extends [never]',
    '    ? Record<string, unknown>',
    '    : Extract<P, { body: unknown }>["body"];',
    '',
    '  type PageNamedActionBody<P, K> = P extends { actions: infer A }',
    '    ? K extends keyof A',
    '      ? A[K] extends { body: infer B }',
    '        ? B',
    '        : Record<string, unknown>',
    '      : never',
    '    : never;',
    '',
    '  type PageActionUrl<K extends string, P> = P extends { body: any }',
    '    ? K',
    '    : P extends { actions: infer A }',
    "      ? `${K}?${keyof A & string}${'' | `&${string}`}`",
    '      : never;',
    '',
    '  export type ResolveActionBody<U extends string> =',
    '    ParseActionUrl<U>["base"] extends keyof PageActionMap',
    '      ? ParseActionUrl<U>["action"] extends never',
    '        ? PageActionBody<PageActionMap[ParseActionUrl<U>["base"]]>',
    '        : PageNamedActionBody<PageActionMap[ParseActionUrl<U>["base"]], ParseActionUrl<U>["action"]>',
    '      : Record<string, unknown>;',
    '',
    '  export type ResolveActionParams<U extends string> =',
    '    ParseActionUrl<U>["base"] extends keyof PageActionMap',
    '      ? PageActionMap[ParseActionUrl<U>["base"]] extends { params: infer P }',
    '        ? P',
    '        : never',
    '      : never;',
    '',
    '  export type HasActionParams<U extends string> =',
    '    [ResolveActionParams<U>] extends [never]',
    '      ? false',
    '      : ResolveActionParams<U> extends Record<string, string> ? true : false;',
    '',
    '  type ActionFormBaseOptions = {',
    '    resetOnSuccess?: boolean;',
    '    throwOnError?: boolean;',
    '  };',
    '',
    '  export type ActionFormOptions<U extends string> = ActionFormBaseOptions &',
    '    (HasActionParams<U> extends true',
    '      ? { params: ResolveActionParams<U> }',
    '      : { params?: never });',
    '',
    '  export type ActionUrl = {',
    '    [K in keyof PageActionMap]: PageActionUrl<K & string, PageActionMap[K]>;',
    '  }[keyof PageActionMap]',
    '',
    '  interface RouteMap {',
  );

  const routesByPattern = new Map<string, Map<string, Array<RouteDefinition>>>();
  for (const route of scan.routes) {
    for (const method of route.methods) {
      let methods = routesByPattern.get(route.pattern);
      if (!methods) {
        methods = new Map();
        routesByPattern.set(route.pattern, methods);
      }
      let sources = methods.get(method);
      if (!sources) {
        sources = [];
        methods.set(method, sources);
      }
      sources.push(route);
    }
  }

  for (const [pattern, methods] of routesByPattern) {
    lines.push(`    ${JSON.stringify(publicRoutePattern(pattern))}: {`);

    for (const [method, sources] of methods) {
      const imports = sources.map((route) => {
        const importPath = relative(outDir, `${routesDir}/${route.filePath}`);
        return `(typeof import(${JSON.stringify(importPath)}))["${method}"]`;
      });
      lines.push(
        `      ${method}: {`,
        `        input: ${imports.map((source) => `ExtractInput<${source}["__validators"]>`).join(' & ')};`,
        `        output: ${imports.map((source) => `Serialize<Awaited<${source}["__output"]>>`).join(' | ')};`,
        '      };',
      );
    }

    lines.push('    };');
    legacyRouteAlias(lines, 'RouteMap', pattern);
  }

  lines.push('  }', '', '  interface WebSocketRouteMap {');

  const websocketsByPattern = new Map<string, Array<WebSocketRouteDefinition>>();
  for (const route of scan.websockets ?? []) {
    const sources = websocketsByPattern.get(route.pattern) ?? [];
    sources.push(route);
    websocketsByPattern.set(route.pattern, sources);
  }

  for (const [pattern, sources] of websocketsByPattern) {
    const imports = sources.map((route) => {
      const importPath = relative(outDir, `${routesDir}/${route.filePath}`);
      return `(typeof import(${JSON.stringify(importPath)}))["default"]["messages"]`;
    });
    lines.push(
      `    ${JSON.stringify(publicRoutePattern(pattern))}: {`,
      `      params: RouteParams<${JSON.stringify(sources[0].params)}>;`,
      `      client: ${imports.map((source) => `ExtractInput<${source}["client"]>`).join(' & ')};`,
      `      server: ${imports.map((source) => `ExtractOutput<${source}["server"]>`).join(' | ')};`,
    );
    const roomSources = sources.filter((route) => route.mode === 'room');
    if (roomSources.length > 0) {
      const actions = roomSources.map((route) => {
        const importPath = relative(outDir, `${routesDir}/${route.filePath}`);
        return `NonNullable<(typeof import(${JSON.stringify(importPath)}))["default"]["actions"]>`;
      });
      lines.push(`      actions: ${actions.join(' | ')};`);
    }
    lines.push('    };');
    legacyRouteAlias(lines, 'WebSocketRouteMap', pattern);
  }

  lines.push('  }');

  // PageActionMap — page actions for typed useForm
  const actionPages = scan.pages.pages.filter(
    (p) => p.methods.includes('action') || p.methods.includes('actions'),
  );
  if (actionPages.length > 0 && pagesDir) {
    lines.push('  interface PageActionMap {');

    // A .dev + .prod page pair shares one pattern: write one key and join the shapes
    // with |. The page at that URL is one environment's page or the other's, so each
    // page's own action body must type-check.
    const bodiesByPattern = new Map<string, Array<Array<string>>>();
    for (const page of actionPages) {
      const hasAction = page.methods.includes('action');
      const hasActions = page.methods.includes('actions');

      if (hasAction && hasActions) {
        throw new Error(
          `pages: Page '${page.pattern}' exports both "action" and "actions". Use one or the other.`,
        );
      }

      const body: Array<string> = [];

      // Page actions are only detected in a companion .server file.
      // oxlint-disable-next-line typescript/no-non-null-assertion -- The page scanner only reports actions from a companion .server file.
      const importPath = relative(outDir, `${pagesDir}/${page.serverPath!}`);
      if (hasActions) {
        const actionsImport = `(typeof import(${JSON.stringify(importPath)}))["actions"]`;
        body.push(
          `      actions: { [K in keyof ${actionsImport}]: {`,
          `        body: ExtractInput<${actionsImport}[K]["__validators"]> extends { body: infer B } ? B : Record<string, unknown>;`,
          '      } };',
        );
      } else {
        const importExpr = `(typeof import(${JSON.stringify(importPath)}))["action"]`;
        body.push(
          `      body: ExtractInput<${importExpr}["__validators"]> extends { body: infer B } ? B : Record<string, unknown>;`,
        );
      }

      if (page.params.length > 0) {
        const paramsType = page.params.map((p) => `${p}: string`).join('; ');
        body.push(`      params: { ${paramsType} };`);
      }

      const bodies = bodiesByPattern.get(page.pattern);
      if (bodies) {
        bodies.push(body);
      } else {
        bodiesByPattern.set(page.pattern, [body]);
      }
    }

    for (const [pattern, bodies] of bodiesByPattern) {
      lines.push(`    ${JSON.stringify(publicRoutePattern(pattern))}: {`);
      bodies.forEach((body, index) => {
        if (index > 0) {
          lines.push('    } | {');
        }
        lines.push(...body);
      });
      lines.push('    };');
      legacyRouteAlias(lines, 'PageActionMap', pattern);
    }

    lines.push('  }');
  }

  lines.push('}', '');

  return { dts: lines.join('\n') };
}
