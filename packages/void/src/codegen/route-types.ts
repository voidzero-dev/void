import { relative } from 'pathslash';
import type { RouteDefinition } from '../router/parse-filename.ts';
import type { ScanResult } from '../router/scan.ts';
import type { WebSocketRouteDefinition } from '../router/websocket.ts';

export type RouteTypesResult = {
  dts: string;
};

/**
 * Generate .void/routes.d.ts content.
 *
 * Uses `typeof import(...)` so TypeScript resolves all types.
 * The codegen generates scaffolding only — never analyzes types itself.
 */
export function generateRouteTypes(
  scan: ScanResult,
  routesDir: string,
  outDir: string,
  pagesDir?: string,
): RouteTypesResult {
  const lines: Array<string> = [];

  lines.push('// Auto-generated by void — do not edit');
  // Top-level export makes this a module so `declare module` below is an
  // augmentation (merges with the real void/routes) rather than an ambient
  // module declaration (which would replace it and hide exported types).
  lines.push('export {}');
  // Inline the Standard Schema types so the generated file is self-contained
  // (no external dependency on @standard-schema/spec)
  lines.push('type StandardSchemaV1<Input = unknown, Output = Input> = {');
  lines.push('  readonly "~standard": {');
  lines.push('    readonly version: 1;');
  lines.push('    readonly vendor: string;');
  lines.push('    readonly validate: (value: unknown) => unknown;');
  lines.push(
    '    readonly types?: { readonly input: Input; readonly output: Output } | undefined;',
  );
  lines.push('  };');
  lines.push('};');
  lines.push('declare namespace StandardSchemaV1 {');
  lines.push('  type InferInput<Schema extends StandardSchemaV1> = NonNullable<');
  lines.push('    Schema["~standard"]["types"]');
  lines.push('  >["input"];');
  lines.push('  type InferOutput<Schema extends StandardSchemaV1> = NonNullable<');
  lines.push('    Schema["~standard"]["types"]');
  lines.push('  >["output"];');
  lines.push('}');
  lines.push('');
  lines.push('type Serialize<T> =');
  lines.push('  T extends Response ? never :');
  lines.push('  T extends Date ? string :');
  lines.push('  T extends bigint ? never :');
  lines.push('  T extends Function ? never :');
  lines.push('  T extends undefined ? never :');
  lines.push('  T extends Array<infer U> ? Array<Serialize<U>> :');
  lines.push(
    '  T extends object ? { [K in keyof T as T[K] extends Function ? never : K]: Serialize<T[K]> } :',
  );
  lines.push('  T;');
  lines.push('');

  // Helper type to extract validated input from __validators
  lines.push('type ExtractInput<V> = {');
  lines.push('  [K in keyof V as V[K] extends StandardSchemaV1 ? K : never]:');
  lines.push('    V[K] extends StandardSchemaV1 ? StandardSchemaV1.InferInput<V[K]> : never;');
  lines.push('};');
  lines.push('');
  lines.push('type ExtractOutput<S> =');
  lines.push('  S extends StandardSchemaV1 ? StandardSchemaV1.InferOutput<S> : never;');
  lines.push('');
  lines.push('type RouteParams<P extends readonly string[]> =');
  lines.push('  P extends readonly [] ? Record<string, never> : { [K in P[number]]: string };');
  lines.push('');

  lines.push('declare module "void/routes" {');
  lines.push('  export interface RouteMap {}');
  lines.push('  export interface WebSocketRouteMap {}');
  lines.push('  export interface PageActionMap {}');
  lines.push('');
  lines.push('  /** Union of known route patterns (keys of the generated RouteMap). */');
  lines.push('  export type RouteName = keyof RouteMap;');
  lines.push('');
  lines.push('  /**');
  lines.push('   * Destination type for rewrites / fallbacks / c.rewrite().');
  lines.push('   *');
  lines.push('   * The `string & {}` branch keeps IDE autocomplete of known routes while');
  lines.push('   * still accepting arbitrary strings (needed for dynamic paths like');
  lines.push('   * `/users/${id}`). When no routes are generated yet, `RouteName` is');
  lines.push('   * `never` and this degenerates to `string & {}`, which is assignable');
  lines.push('   * from any string.');
  lines.push('   */');
  lines.push('  export type RewriteDestination = RouteName | (string & {});');
  lines.push('');
  lines.push(
    '  export type ParseActionUrl<U extends string> = U extends `${infer Base}?${infer Action}` ? {',
  );
  lines.push('    base: Base;');
  lines.push('    action: Action;');
  lines.push('  } : {');
  lines.push('    base: U;');
  lines.push('    action: never;');
  lines.push('  };');
  lines.push('');
  lines.push('  export type ResolveActionBody<U extends string> =');
  lines.push('    ParseActionUrl<U>["base"] extends keyof PageActionMap');
  lines.push('      ? ParseActionUrl<U>["action"] extends never');
  lines.push('        ? PageActionMap[ParseActionUrl<U>["base"]] extends { body: infer B }');
  lines.push('          ? B');
  lines.push('          : Record<string, unknown>');
  lines.push('        : PageActionMap[ParseActionUrl<U>["base"]] extends { actions: infer A }');
  lines.push('          ? ParseActionUrl<U>["action"] extends keyof A');
  lines.push('            ? A[ParseActionUrl<U>["action"]] extends { body: infer B }');
  lines.push('              ? B');
  lines.push('              : Record<string, unknown>');
  lines.push('            : never');
  lines.push('          : never');
  lines.push('      : Record<string, unknown>;');
  lines.push('');
  lines.push('  export type ResolveActionParams<U extends string> =');
  lines.push('    ParseActionUrl<U>["base"] extends keyof PageActionMap');
  lines.push('      ? PageActionMap[ParseActionUrl<U>["base"]] extends { params: infer P }');
  lines.push('        ? P');
  lines.push('        : never');
  lines.push('      : never;');
  lines.push('');
  lines.push('  export type HasActionParams<U extends string> =');
  lines.push('    [ResolveActionParams<U>] extends [never]');
  lines.push('      ? false');
  lines.push('      : ResolveActionParams<U> extends Record<string, string> ? true : false;');
  lines.push('');
  lines.push('  type ActionFormBaseOptions = { resetOnSuccess?: boolean };');
  lines.push('');
  lines.push('  export type ActionFormOptions<U extends string> = ActionFormBaseOptions &');
  lines.push('    (HasActionParams<U> extends true');
  lines.push('      ? { params: ResolveActionParams<U> }');
  lines.push('      : { params?: never });');
  lines.push('');
  lines.push('  export type ActionUrl =');
  lines.push('    | {');
  lines.push(
    '        [K in keyof PageActionMap]: PageActionMap[K] extends { body: any } ? K : never;',
  );
  lines.push('      }[keyof PageActionMap]');
  lines.push('    | {');
  lines.push('        [K in keyof PageActionMap]: PageActionMap[K] extends { actions: infer A }');
  lines.push('          ? `${K & string}?${keyof A & string}`');
  lines.push('          : never;');
  lines.push('      }[keyof PageActionMap]');
  lines.push('');
  lines.push('  interface RouteMap {');

  const routesByPattern = new Map<string, Map<string, Array<RouteDefinition>>>();
  for (const route of scan.routes) {
    for (const method of route.methods) {
      let methods = routesByPattern.get(route.pattern);
      if (!methods) {
        methods = new Map();
        routesByPattern.set(route.pattern, methods);
      }
      let sources = methods.get(method);
      if (!sources) {
        sources = [];
        methods.set(method, sources);
      }
      sources.push(route);
    }
  }

  for (const [pattern, methods] of routesByPattern) {
    lines.push(`    ${JSON.stringify(pattern)}: {`);

    for (const [method, sources] of methods) {
      const imports = sources.map((route) => {
        const importPath = relative(outDir, `${routesDir}/${route.filePath}`);
        return `(typeof import(${JSON.stringify(importPath)}))["${method}"]`;
      });
      lines.push(`      ${method}: {`);
      lines.push(
        `        input: ${imports.map((source) => `ExtractInput<${source}["__validators"]>`).join(' & ')};`,
      );
      lines.push(
        `        output: ${imports.map((source) => `Serialize<Awaited<${source}["__output"]>>`).join(' | ')};`,
      );
      lines.push('      };');
    }

    lines.push('    };');
  }

  lines.push('  }');
  lines.push('');
  lines.push('  interface WebSocketRouteMap {');

  const websocketsByPattern = new Map<string, Array<WebSocketRouteDefinition>>();
  for (const route of scan.websockets ?? []) {
    const sources = websocketsByPattern.get(route.pattern) ?? [];
    sources.push(route);
    websocketsByPattern.set(route.pattern, sources);
  }

  for (const [pattern, sources] of websocketsByPattern) {
    const imports = sources.map((route) => {
      const importPath = relative(outDir, `${routesDir}/${route.filePath}`);
      return `(typeof import(${JSON.stringify(importPath)}))["default"]["messages"]`;
    });
    lines.push(`    ${JSON.stringify(pattern)}: {`);
    lines.push(`      params: RouteParams<${JSON.stringify(sources[0]!.params)}>;`);
    lines.push(
      `      client: ${imports.map((source) => `ExtractInput<${source}["client"]>`).join(' & ')};`,
    );
    lines.push(
      `      server: ${imports.map((source) => `ExtractOutput<${source}["server"]>`).join(' | ')};`,
    );
    lines.push('    };');
  }

  lines.push('  }');

  // PageActionMap — page actions for typed useForm
  const actionPages = scan.pages.pages.filter(
    (p) => p.methods.includes('action') || p.methods.includes('actions'),
  );
  if (actionPages.length > 0 && pagesDir) {
    lines.push('  interface PageActionMap {');

    // A .dev + .prod page pair shares one pattern: write one key and join the shapes
    // with |. The page at that URL is one environment's page or the other's, so each
    // page's own action body must type-check.
    const bodiesByPattern = new Map<string, Array<Array<string>>>();
    for (const page of actionPages) {
      const hasAction = page.methods.includes('action');
      const hasActions = page.methods.includes('actions');

      if (hasAction && hasActions) {
        throw new Error(
          `pages: Page '${page.pattern}' exports both "action" and "actions". Use one or the other.`,
        );
      }

      const body: Array<string> = [];

      // Page actions are only detected in a companion .server file.
      const importPath = relative(outDir, `${pagesDir}/${page.serverPath!}`);
      if (hasActions) {
        const actionsImport = `(typeof import(${JSON.stringify(importPath)}))["actions"]`;
        body.push(`      actions: { [K in keyof ${actionsImport}]: {`);
        body.push(
          `        body: ExtractInput<${actionsImport}[K]["__validators"]> extends { body: infer B } ? B : Record<string, unknown>;`,
        );
        body.push('      } };');
      } else {
        const importExpr = `(typeof import(${JSON.stringify(importPath)}))["action"]`;
        body.push(
          `      body: ExtractInput<${importExpr}["__validators"]> extends { body: infer B } ? B : Record<string, unknown>;`,
        );
      }

      if (page.params.length > 0) {
        const paramsType = page.params.map((p) => `${p}: string`).join('; ');
        body.push(`      params: { ${paramsType} };`);
      }

      const bodies = bodiesByPattern.get(page.pattern);
      if (bodies) {
        bodies.push(body);
      } else {
        bodiesByPattern.set(page.pattern, [body]);
      }
    }

    for (const [pattern, bodies] of bodiesByPattern) {
      lines.push(`    ${JSON.stringify(pattern)}: {`);
      bodies.forEach((body, index) => {
        if (index > 0) {
          lines.push('    } | {');
        }
        lines.push(...body);
      });
      lines.push('    };');
    }

    lines.push('  }');
  }

  lines.push('}');
  lines.push('');

  return { dts: lines.join('\n') };
}
