const managedBindings = new Set(['DB', 'KV', 'STORAGE', 'AI', 'SANDBOX', 'ASSETS']);

/** Generate types for explicitly configured bindings without changing managed types. */
export function generateBindingTypes(config: VoidConfig): string | null {
  if (config.target && config.target !== 'cloudflare') {
    return null;
  }
  const bindings = new Map<string, string>();
  for (const [path, nameField, type] of bindingTypes) {
    let value: unknown = config.cloudflare;
    for (const field of path.split('.')) {
      value =
        value && typeof value === 'object' ? (value as Record<string, unknown>)[field] : undefined;
    }
    for (const entry of Array.isArray(value) ? value : [value]) {
      const name =
        entry && typeof entry === 'object'
          ? (entry as Record<string, unknown>)[nameField]
          : undefined;
      if (typeof name === 'string' && !managedBindings.has(name)) {
        bindings.set(name, type);
      }
    }
  }
  if (bindings.size === 0) {
    return null;
  }
  return [
    '// Auto-generated by void — do not edit',
    'export {};',
    'declare global {',
    '  interface VoidGeneratedEnvBindings {',
    ...[...bindings]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, type]) => `    ${JSON.stringify(name)}: ${type};`),
    '  }',
    '}',
    '',
  ].join('\n');
}

export function syncBindingTypes(root: string, config: VoidConfig): void {
  const path = join(root, '.void', 'bindings.d.ts');
  const dts = generateBindingTypes(config);
  if (dts) {
    writeFileIfChanged(path, dts);
  } else {
    rmSync(path, { force: true });
  }
}
