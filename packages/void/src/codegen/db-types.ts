import { join } from 'pathslash';
import type { SchemaLocation } from '../drizzle/discover.ts';
import { writeFileIfChanged } from './write-if-changed.ts';

export const DRIZZLE_OPERATORS =
  'sql, eq, ne, gt, gte, lt, lte, and, or, not, desc, asc, like, ilike, notLike, inArray, notInArray, isNull, isNotNull, between, notBetween, exists, notExists, count, sum, avg, min, max';

export const DRIZZLE_TYPES = 'AnyColumn, SQL, SQLWrapper, BatchItem';

const DIALECT_DB_TYPES = {
  sqlite: {
    type: 'DrizzleD1Database',
    from: 'void/_db',
    arg: 'd1: D1Database, options?: { session?: D1SessionConstraint }',
  },
  postgresql: { type: 'NodePgDatabase', from: 'void/_db-pg', arg: 'connectionString: string' },
  mysql: { type: 'MySql2Database', from: 'void/_db-mysql', arg: 'connectionString: string' },
} as const;

/**
 * Generate `.void/db.d.ts` with Drizzle types referencing the user's schema.
 *
 * This is a proper module file (not `declare module`) whose types override
 * the base `void/db` package via a tsconfig `paths` redirect:
 *   "void/db": ["./.void/db.d.ts"]
 *
 * Imports reference `void/_db` (internal subpath pointing at the same
 * base module) to avoid circular resolution through the paths redirect.
 */
export function generateDbDts(
  outDir: string,
  schema: SchemaLocation | null,
  dialect: 'sqlite' | 'postgresql' | 'mysql',
): boolean {
  const { type, from, arg } = DIALECT_DB_TYPES[dialect];
  const schemaType = schema ? 'Schema' : 'Record<string, never>';

  const lines = [
    '// Auto-generated by void — do not edit',
    ...(dialect === 'sqlite' ? ['/// <reference types="@cloudflare/workers-types" />'] : []),
    `import type { ${type} } from "${from}";`,
    ...(schema ? ['import type * as schema from "@schema";', 'type Schema = typeof schema;'] : []),
    `export declare const db: ${type}<${schemaType}>;`,
    `export declare function createDb(${arg}): ${type}<${schemaType}>;`,
    `export { ${DRIZZLE_OPERATORS} } from "void/_db";`,
    `export type { ${DRIZZLE_TYPES} } from "void/_db";`,
    `export type { ${type} } from "${from}";`,
    '',
  ];

  return writeFileIfChanged(join(outDir, 'db.d.ts'), lines.join('\n'));
}
