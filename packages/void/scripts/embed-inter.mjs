// Regenerate the checked-in font module with `node packages/void/scripts/embed-inter.mjs`.
// Normal builds are offline: only this maintainer command downloads the pinned Inter 4.1 sources.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const revision = 'e3a3d4c57d5ecc01453a575621882a384c1995a3';
const base = `https://raw.githubusercontent.com/rsms/inter/${revision}/`;
async function download(path, sha256) {
  const response = await fetch(base + path);
  assert(response.ok, `${path}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  assert.equal(createHash('sha256').update(bytes).digest('hex'), sha256, path);
  return bytes;
}

const [woff2, ttf, license] = await Promise.all([
  download(
    'docs/font-files/InterVariable.woff2',
    '693b77d4f32ee9b8bfc995589b5fad5e99adf2832738661f5402f9978429a8e3',
  ),
  download(
    'docs/font-files/InterVariable.ttf',
    '4989b125924991b90d05b2d16e0e388c48f7d5bb8b30539bbf9c755278d0ccaf',
  ),
  download('LICENSE.txt', '262481e844521b326f5ecd053e59b98c8b2da78c8ee1bdbb6e8174305e54935a'),
]);

// Read the matching TTF's Unicode cmap (format 12), not a script-wide approximation.
// Glyph 0 is .notdef and must never count as coverage.
let cmap;
for (let i = 0; i < ttf.readUInt16BE(4); i++) {
  const record = 12 + i * 16;
  if (ttf.toString('ascii', record, record + 4) === 'cmap') {
    cmap = ttf.readUInt32BE(record + 8);
  }
}
assert.notEqual(cmap, undefined);
let format12;
for (let i = 0; i < ttf.readUInt16BE(cmap + 2); i++) {
  const offset = cmap + ttf.readUInt32BE(cmap + 4 + i * 8 + 4);
  if (ttf.readUInt16BE(offset) === 12) {
    format12 = offset;
    break;
  }
}
assert.notEqual(format12, undefined);
const ranges = [];
for (let i = 0; i < ttf.readUInt32BE(format12 + 12); i++) {
  const offset = format12 + 16 + i * 12;
  const start = ttf.readUInt32BE(offset) + (ttf.readUInt32BE(offset + 8) === 0 ? 1 : 0);
  const end = ttf.readUInt32BE(offset + 4);
  if (start > end) {
    continue;
  }
  const previous = ranges.at(-1);
  if (previous && previous[1] + 1 === start) {
    previous[1] = end;
  } else {
    ranges.push([start, end]);
  }
}

const output = new URL('../src/runtime/image-inter.ts', import.meta.url);
await writeFile(
  output,
  `/**
 * Generated by scripts/embed-inter.mjs. Do not edit.
 * Inter 4.1, ${revision}; unmodified InterVariable.woff2.
 * Copyright (c) 2016 The Inter Project Authors (https://github.com/rsms/inter).
 * SIL Open Font License 1.1: see licenses/Inter.txt in the void package.
 */
import { base64ToBytes } from './base64.ts';

export const interCoverage: ReadonlyArray<readonly [number, number]> = [
${ranges.map(([start, end]) => `  [0x${start.toString(16)}, 0x${end.toString(16)}],`).join('\n')}
];

let bytes: Uint8Array | undefined;
export function interData(): Uint8Array {
  return bytes ??= base64ToBytes('${woff2.toString('base64')}');
}
`,
);
await mkdir(new URL('../licenses/', import.meta.url), { recursive: true });
await writeFile(new URL('../licenses/Inter.txt', import.meta.url), license);
execFileSync('vp', ['fmt', fileURLToPath(output)], { stdio: 'inherit' });
console.log(`Embedded ${woff2.length} bytes of Inter with ${ranges.length} coverage ranges.`);
